/// \file
/// \brief ISO 4217: every currency as a type (`snicholls::currency::AUD`) and as a constexpr table, from the lists
/// SIX publishes, with the countries using it, and CLDR's cash rounding and symbol.
/// \ingroup core
///
/// **Overview.** ISO 4217 codes are immutable, so they are compiled in. Each code is a type in
/// `snicholls::currency`, named by the code itself (`AUD`, `EUR`, `XAU`). Capitals are kept deliberately, so that
/// the name is the code (lowercase would make `TRY`, the Turkish lira, the keyword `try`). Each type has
/// `static constexpr` member functions:
/// - `code()`, `name()` and `numeric()`;
/// - `scale()`, the ISO minor units, where ISO gives them;
/// - `withdrawn()`, for a historic code;
/// - `countries()`, for a current code: the ISO 3166-1 alpha-2 codes of the countries using it, from SIX's list one
///   (the entities of list one that are not countries, such as EUROPEAN UNION, are left out), sorted;
/// - `cash_scale()` and `cash_rounding()`, where Unicode CLDR gives a cash rule: a cash amount is a multiple of
///   `cash_rounding()` x 10^-`cash_scale()` (CHF 5 x 10^-2 = 0.05, DKK 0.50, SEK whole kronor).
///
/// The display symbol is presentation, so it is not a member: each type declares `attributes()` (found by ADL,
/// `meta/attributes.hpp`) with a `label` holding CLDR's root-locale symbol ("A$", "€", "JP¥", "US$"; the code where
/// CLDR gives none) and, where ISO gives a scale, `minor_units`. Every printer that reads attributes shows it:
/// `attribute_or(currency::AUD{}, label{""}).text` is "A$".
///
/// \snippet money/iso4217_demo.cpp metadata
///
/// A type with a scale models `currency_like` and `asset_like`, so `asset_v<currency::AUD>` and
/// `money_of<currency::AUD>` work. The same data is a sorted table for codes that arrive at run time:
/// `find_iso4217("AUD")`, `find_iso4217(36)`, `iso4217_asset("AUD")`. The literal `"AUD"_iso4217` is checked by the
/// compiler.
///
/// The table is generated by `scripts/generate_iso4217.py` from SIX's list one (current currencies and funds) and
/// list three (historic denominations), committed unmodified under `scripts/data/iso4217/`. The publication date of
/// list one is `iso4217_published`. A historic code (`ANG`, withdrawn 2025-03) still resolves, so old books do.
/// The countries come through the curated `scripts/data/iso4217/entities.tsv`, which maps each entity of list one to
/// its alpha-2; cash rules and symbols from the subset of CLDR under `scripts/data/cldr/` (release
/// `iso4217_cldr_version`, the Unicode licence). The table's rows carry the same: `countries`, `symbol`,
/// `cash_scale` (-1 where CLDR gives no cash rule) and `cash_rounding`.
///
/// \snippet money/iso4217_demo.cpp iso4217
///
/// **Relationships.** `money/asset.hpp`, `concepts/asset.hpp`, `money/money.hpp`, `money/native.hpp` (chain
/// assets, which are not ISO), `country.hpp` (whose `currencies()` are the inverse of `countries()`, funds left
/// out), `display.hpp` (`label`, `minor_units`). Group: \ref core.
///
/// **Implementations.** One generated type per code, and the generated table.
///
/// **Guarantees.**
/// - constexpr, `noexcept`, no allocation.
/// - The table is sorted by alphabetic code. A code in both lists keeps list one's entry.
/// - A code withdrawn more than once keeps its latest withdrawal.
///
/// **Errors.**
/// - `find_iso4217` returns `nullptr` for an unknown code.
/// - `iso4217_asset` returns `std::nullopt` for an unknown code, or one with no ISO scale.
/// - `"XXX"_iso4217` for such a code is a compile error.
///
/// **Performance.** Binary search over the generated rows, at compile time where the code is a constant. Not
/// benchmarked.
///
/// **Tests and demos.** `tests/money/iso4217_test.cpp` (checked against SIX's XML through Python's
/// `xml.etree`, the CTest `generated.iso4217_up_to_date`; the countries against pycountry and the cash rules and
/// symbols against babel through `tests/fixtures/money/currencies.tsv`, the CTest
/// `generated.country_fixtures_up_to_date`), `demos/money/iso4217_demo.cpp`.
///
/// **Dependencies.** `<cstddef>`, `<cstdint>`, `<optional>`, `<span>`, `<string_view>`, `money/asset.hpp`,
/// `detail/iso4217_table.hpp` (about 300 types and rows: heavier than it looks, so include it only where needed),
/// which includes `display.hpp` and so `<ostream>`.
///
/// **Known issues.**
/// - ISO gives no minor units to the precious metals (XAU, XAG, XPT, XPD), the SDR (XDR) and the funds. Those types
///   need `with_scale<currency::XAU, 18>`.
/// - SIX's historic list has no minor units, so historic codes need `with_scale` too.
/// - `--latest` on the generator reports a newer SIX list; regenerate when SIX publishes one.
/// - CLDR's digits differ from ISO's for a few codes (AFN, IQD); `scale()` is always ISO's, and CLDR only decides
///   the cash rule. Root-locale symbols are deliberately unambiguous ("US$", "JP¥"), not a locale's ("$", "¥").
///
/// **Status.** New in 0.22.0; countries, cash rules and symbols new in 0.23.0.

#ifndef snicholls_core_money_iso4217_hpp
#define snicholls_core_money_iso4217_hpp

#include <snicholls/core/detail/iso4217_table.hpp>
#include <snicholls/core/money/asset.hpp>

#include <cstddef>
#include <cstdint>
#include <optional>
#include <span>
#include <string_view>

namespace snicholls {

    namespace detail {
        // The row of an alphabetic code, or iso4217_rows.size(). An index, not a pointer: GCC cannot compare a
        // pointer into the table with nullptr in a constant expression.
        constexpr std::size_t iso4217_index(std::string_view code) noexcept
        {
            std::size_t lo = 0, hi = iso4217_rows.size();
            while (lo < hi) {
                const std::size_t mid = lo + (hi - lo) / 2;
                const std::string_view c = iso4217_rows[mid].code;
                if (c == code)
                    return mid;
                if (c < code)
                    lo = mid + 1;
                else
                    hi = mid;
            }
            return iso4217_rows.size();
        }
    } // namespace detail

    /// \brief One ISO 4217 code: `code`, `name`, `numeric`, `scale` (-1 where ISO gives none), `withdrawn`
    /// (the date SIX gives, such as "2025-03" or "1989 to 1990", for a historic code; empty for a current one),
    /// `countries` (alpha-2, sorted), `symbol` (CLDR's root-locale symbol, or the code), `cash_scale` (-1 where CLDR
    /// gives no cash rule) and `cash_rounding`.
    using iso4217_entry = detail::iso4217_row;

    /// \brief The publication date of the ISO 4217 list the table was generated from (SIX list one).
    inline constexpr std::string_view iso4217_published = detail::iso4217_published;

    /// \brief The Unicode CLDR release the cash rules and symbols come from.
    inline constexpr std::string_view iso4217_cldr_version = detail::iso4217_cldr_version;

    /// \brief Every code, current and historic, sorted by alphabetic code.
    /// \return The table.
    [[nodiscard]] constexpr std::span<const iso4217_entry> iso4217_entries() noexcept { return detail::iso4217_rows; }

    /// \brief The entry with this alphabetic code.
    /// \param code Three capitals.
    /// \return The entry, or `nullptr` if ISO 4217 has no such code.
    [[nodiscard]] constexpr const iso4217_entry* find_iso4217(std::string_view code) noexcept
    {
        const std::size_t i = detail::iso4217_index(code);
        return i < detail::iso4217_rows.size() ? &detail::iso4217_rows[i] : nullptr;
    }

    /// \brief The current entry with this numeric code (a historic one if no current code has it).
    /// \param numeric The numeric code.
    /// \return The entry, or `nullptr`.
    [[nodiscard]] constexpr const iso4217_entry* find_iso4217(std::uint16_t numeric) noexcept
    {
        const iso4217_entry* historic = nullptr;
        for (const auto& e : detail::iso4217_rows) {
            if (e.numeric != numeric)
                continue;
            if (e.withdrawn.empty())
                return &e;
            historic = historic ? historic : &e;
        }
        return historic;
    }

    /// \brief The asset of an ISO 4217 code that has an ISO scale.
    /// \param code Three capitals.
    /// \return The asset, or `std::nullopt` for an unknown code or one ISO gives no minor units.
    [[nodiscard]] constexpr std::optional<asset> iso4217_asset(std::string_view code) noexcept
    {
        const std::size_t i = detail::iso4217_index(code);
        if (i >= detail::iso4217_rows.size() || detail::iso4217_rows[i].scale < 0)
            return std::nullopt;
        return make_asset(detail::iso4217_rows[i].code, static_cast<unsigned>(detail::iso4217_rows[i].scale));
    }

    namespace literals {
        /// \brief `"AUD"_iso4217`: the asset of an ISO 4217 code, checked by the compiler.
        /// \param s The code.
        /// \param n Its length.
        /// \return The asset; an unknown code, or one with no ISO scale, is a compile error.
        consteval asset operator""_iso4217(const char* s, std::size_t n)
        {
            const auto a = iso4217_asset(std::string_view{s, n});
            if (!a)
                throw "snicholls::operator\"\"_iso4217: not an ISO 4217 code with minor units";   // a compile error
            return *a;
        }
    } // namespace literals

} // namespace snicholls

#endif // snicholls_core_money_iso4217_hpp
