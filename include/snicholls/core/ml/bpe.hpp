/// \brief The rank a vocabulary lookup returns for bytes that are not a token.
inline constexpr std::uint32_t bpe_no_rank = 0xffffffffu;

/// \brief Why `bpe_encode_piece` or `bpe_decode` failed.
/// \ingroup core
enum class bpe_error
{
    output_too_small,    ///< The output span is shorter than the piece (or than the decoded bytes).
    scratch_too_small,   ///< The scratch span is shorter than `bpe_scratch_size(piece.size())`.
    unknown_bytes,       ///< A byte (or, decoding, a token id) is not in the vocabulary.
};

/// \brief One part of a piece during merging: where it starts, and the rank of it merged with the next part.
/// \ingroup core
struct bpe_part
{
    std::uint32_t start;   ///< The offset of the part in the piece.
    std::uint32_t rank;    ///< The rank of this part and the next together, or `bpe_no_rank`.
};

/// \brief A vocabulary lookup: bytes to their rank, or `bpe_no_rank`.
/// \ingroup core
template <typename F>
concept bpe_vocabulary = requires(F& f, std::string_view bytes) {
    { f(bytes) } -> std::convertible_to<std::uint32_t>;
};

namespace detail::bpe
{
    // The rank of parts i and i+1 merged with i+2: the bytes from part i to part i+3. A function, not a lambda
    // capturing the lookup: MSVC cannot read a captured reference to a function during constant evaluation.
    template <typename Rank>
    constexpr std::uint32_t rank_after_merge(std::string_view piece, Rank& rank, const bpe_part* parts, std::size_t len, std::size_t i)
    {
        if (i + 3 < len)
            return rank(piece.substr(parts[i].start, parts[i + 3].start - parts[i].start));
        return bpe_no_rank;
    }
} // namespace detail::bpe

/// \brief The scratch parts `bpe_encode_piece` needs for a piece of `n` bytes: `n + 1`.
/// \param n The piece's length.
/// \return The number of `bpe_part`s.
constexpr std::size_t bpe_scratch_size(std::size_t n) noexcept { return n + 1; }

/// \brief Encodes one piece (a match of the tokenizer's split pattern) into tokens, as tiktoken does.
/// \tparam Rank A `bpe_vocabulary`.
/// \param piece The bytes of the piece.
/// \param rank The vocabulary: bytes to rank, `bpe_no_rank` if not a token.
/// \param out Receives the tokens: `piece.size()` slots always suffice; one does when the piece is a token.
/// \param scratch Working space: at least `bpe_scratch_size(piece.size())` parts.
/// \return The number of tokens written, or why not.
template <bpe_vocabulary Rank>
constexpr result<std::size_t, bpe_error> bpe_encode_piece(std::string_view piece, Rank&& rank, std::span<std::uint32_t> out,
                                                          std::span<bpe_part> scratch)
{
    const std::size_t n = piece.size();
    if (n == 0)
        return ok(std::size_t{0});
    if (out.empty())
        return err(bpe_error::output_too_small);
    if (const std::uint32_t whole = rank(piece); whole != bpe_no_rank) {   // the common case: one token, no scratch
        out[0] = whole;
        return ok(std::size_t{1});
    }
    if (out.size() < n)
        return err(bpe_error::output_too_small);
    if (scratch.size() < bpe_scratch_size(n))
        return err(bpe_error::scratch_too_small);

    // parts[i] = (start of part i, rank of parts i and i+1 merged); the last two are sentinels
    std::size_t len = n + 1;
    bpe_part* parts = scratch.data();
    std::uint32_t min_rank = bpe_no_rank;
    std::size_t min_at = 0;
    for (std::size_t i = 0; i + 1 < n; ++i) {
        const std::uint32_t r = rank(piece.substr(i, 2));
        if (r < min_rank) {
            min_rank = r;
            min_at = i;
        }
        parts[i] = {static_cast<std::uint32_t>(i), r};
    }
    parts[n - 1] = {static_cast<std::uint32_t>(n - 1), bpe_no_rank};
    parts[n] = {static_cast<std::uint32_t>(n), bpe_no_rank};

    while (min_rank != bpe_no_rank) {
        const std::size_t i = min_at;
        if (i > 0)
            parts[i - 1].rank = detail::bpe::rank_after_merge(piece, rank, parts, len, i - 1);
        parts[i].rank = detail::bpe::rank_after_merge(piece, rank, parts, len, i);
        for (std::size_t k = i + 1; k + 1 < len; ++k)   // remove part i+1
            parts[k] = parts[k + 1];
        --len;
        min_rank = bpe_no_rank;
        for (std::size_t k = 0; k + 1 < len; ++k)
            if (parts[k].rank < min_rank) {
                min_rank = parts[k].rank;
                min_at = k;
            }
    }

    // The tokens are the ranks of the parts. Only a part of one byte can be missing (a merged part is a token by
    // construction), and then the vocabulary is not byte-level.
    const std::size_t count = len - 1;
    for (std::size_t k = 0; k < count; ++k) {
        out[k] = rank(piece.substr(parts[k].start, parts[k + 1].start - parts[k].start));
        if (out[k] == bpe_no_rank)
            return err(bpe_error::unknown_bytes);
    }
    return ok(count);
}

namespace detail::bpe
{
    // bpe_encode_long_piece's helpers. Functions, not lambdas capturing the lookup, as rank_after_merge: MSVC
    // cannot read a captured reference to a function during constant evaluation.

    // Heap order: the lower rank, then the leftmost start
    constexpr bool long_before(const bpe_part& a, const bpe_part& b) noexcept
    {
        return a.rank < b.rank || (a.rank == b.rank && a.start < b.start);
    }

    constexpr void long_push(bpe_part* heap, std::size_t& size, bpe_part e) noexcept
    {
        std::size_t i = size++;
        while (i > 0) {
            const std::size_t p = (i - 1) / 2;
            if (!long_before(e, heap[p]))
                break;
            heap[i] = heap[p];
            i = p;
        }
        heap[i] = e;
    }

    constexpr bpe_part long_pop(bpe_part* heap, std::size_t& size) noexcept
    {
        const bpe_part top = heap[0];
        const bpe_part e = heap[--size];
        std::size_t i = 0;
        for (;;) {
            std::size_t c = 2 * i + 1;
            if (c >= size)
                break;
            if (c + 1 < size && long_before(heap[c + 1], heap[c]))
                ++c;
            if (!long_before(heap[c], e))
                break;
            heap[i] = heap[c];
            i = c;
        }
        if (size > 0)
            heap[i] = e;
        return top;
    }

    // The rank of the part at i merged with the next: the bytes from i to the end of the next part
    template <typename Rank>
    constexpr std::uint32_t long_pair_rank(std::string_view piece, Rank& rank, const bpe_part* link, std::uint32_t i)
    {
        const std::uint32_t j = link[i].start;
        if (j >= piece.size())
            return bpe_no_rank;
        return rank(piece.substr(i, link[j].start - i));
    }
} // namespace detail::bpe

/// \brief The scratch parts `bpe_encode_long_piece` needs for a piece of `n` bytes: `5n + 1` (the links, 2n,
/// and the heap, 3n: n - 1 initial pairs and at most two more per merge).
/// \param n The piece's length.
/// \return The number of `bpe_part`s.
constexpr std::size_t bpe_long_scratch_size(std::size_t n) noexcept { return 5 * n + 1; }

/// \brief The piece length from which `bpe_encode_long_piece` is at least as fast as `bpe_encode_piece` on
/// every shape measured (see Performance).
inline constexpr std::size_t bpe_long_piece_threshold = 1024;

/// \brief Encodes one piece into the same tokens as `bpe_encode_piece`, in O(n log n): for long pieces.
/// \tparam Rank A `bpe_vocabulary`.
/// \param piece The bytes of the piece.
/// \param rank The vocabulary: bytes to rank, `bpe_no_rank` if not a token.
/// \param out Receives the tokens: `piece.size()` slots always suffice; one does when the piece is a token.
/// \param scratch Working space: at least `bpe_long_scratch_size(piece.size())` parts.
/// \return The number of tokens written, or why not.
///
/// The rescan of `bpe_encode_piece` becomes a binary heap of candidate pairs ordered by (rank, start): its
/// minimum is the lowest rank, and among equal ranks the leftmost, the pair tiktoken merges. A merge changes the
/// pair to its left and the pair at its own start; their new ranks are pushed and the old entries are skipped
/// when they surface. An entry is current exactly when its part is alive and its rank is the part's pair rank
/// now: the pair at a start only ever grows, and distinct byte strings have distinct ranks.
template <bpe_vocabulary Rank>
constexpr result<std::size_t, bpe_error> bpe_encode_long_piece(std::string_view piece, Rank&& rank, std::span<std::uint32_t> out,
                                                               std::span<bpe_part> scratch)
{
    const std::size_t n = piece.size();
    if (n == 0)
        return ok(std::size_t{0});
    if (out.empty())
        return err(bpe_error::output_too_small);
    if (const std::uint32_t whole = rank(piece); whole != bpe_no_rank) {   // the common case: one token, no scratch
        out[0] = whole;
        return ok(std::size_t{1});
    }
    if (out.size() < n)
        return err(bpe_error::output_too_small);
    if (scratch.size() < bpe_long_scratch_size(n))
        return err(bpe_error::scratch_too_small);

    // link[i] = {start of the next part, rank of part i merged with it}, for a part starting at i;
    // back[i] = {start of the previous part (n for none), 1 while the part is alive, 0 once merged away}
    bpe_part* link = scratch.data();
    bpe_part* back = link + n;
    bpe_part* heap = back + n;   // {start, rank}, a min-heap by (rank, start)
    std::size_t size = 0;

    for (std::uint32_t i = 0; i < n; ++i) {
        link[i] = {i + 1, bpe_no_rank};
        back[i] = {i == 0 ? static_cast<std::uint32_t>(n) : i - 1, 1};
    }
    for (std::uint32_t i = 0; i + 1 < n; ++i)
        if ((link[i].rank = rank(piece.substr(i, 2))) != bpe_no_rank)
            detail::bpe::long_push(heap, size, {i, link[i].rank});

    while (size > 0) {
        const bpe_part e = detail::bpe::long_pop(heap, size);
        const std::uint32_t i = e.start;
        if (back[i].rank == 0 || link[i].rank != e.rank)   // merged away, or its pair has grown since
            continue;
        const std::uint32_t j = link[i].start;   // part j joins part i
        const std::uint32_t k = link[j].start;
        back[j].rank = 0;
        link[i].start = k;
        if (k < n)
            back[k].start = i;
        if ((link[i].rank = detail::bpe::long_pair_rank(piece, rank, link, i)) != bpe_no_rank)
            detail::bpe::long_push(heap, size, {i, link[i].rank});
        if (const std::uint32_t p = back[i].start; p < n)
            if ((link[p].rank = detail::bpe::long_pair_rank(piece, rank, link, p)) != bpe_no_rank)
                detail::bpe::long_push(heap, size, {p, link[p].rank});
    }

    // The tokens are the ranks of the parts; as in bpe_encode_piece, only a single byte can be missing
    std::size_t count = 0;
    for (std::uint32_t i = 0; i < n; i = link[i].start) {
        out[count] = rank(piece.substr(i, link[i].start - i));
        if (out[count] == bpe_no_rank)
            return err(bpe_error::unknown_bytes);
        ++count;
    }
    return ok(count);
}

/// \brief Decodes tokens to bytes: the concatenation of each token's bytes.
/// \tparam Bytes A callable `bytes(std::uint32_t id) -> std::string_view`, empty for an unknown id.
/// \param tokens The tokens.
/// \param bytes The vocabulary's reverse lookup.
/// \param out Receives the bytes.
/// \return The number of bytes written, or `unknown_bytes` / `output_too_small`; `out` may be partly written.
template <typename Bytes>
    requires requires(Bytes& b, std::uint32_t id) {
        { b(id) } -> std::convertible_to<std::string_view>;
    }
constexpr result<std::size_t, bpe_error> bpe_decode(std::span<const std::uint32_t> tokens, Bytes&& bytes, std::span<char> out)
{
    std::size_t at = 0;
    for (const std::uint32_t id : tokens) {
        const std::string_view b = bytes(id);
        if (b.empty())
            return err(bpe_error::unknown_bytes);
        if (out.size() - at < b.size())
            return err(bpe_error::output_too_small);
        for (const char c : b)
            out[at++] = c;
    }
    return ok(at);
}

