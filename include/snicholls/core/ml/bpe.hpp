/// \file
/// \brief `snicholls::ml::bpe_encode_piece` and `bpe_decode`: byte-level BPE, token for token what tiktoken gives, with the vocabulary as the caller's lookup and no allocation.
/// \ingroup core
///
/// **Overview.** Byte-level byte-pair encoding as GPT-2, GPT-4, LLaMA 3 and nanochat use it. A tokenizer first
/// splits text into pieces with a regular expression (the split pattern is the tokenizer's, and lives with it,
/// not here); each piece is then encoded on its own:
///
/// 1. If the whole piece is a token, that token.
/// 2. Otherwise start from its bytes and repeatedly merge the adjacent pair whose concatenation has the lowest
///    rank, the leftmost when ranks tie, until no adjacent pair is a token. The ranks of the remaining parts are
///    the tokens.
///
/// This is tiktoken's `byte_pair_merge`, step for step, so the tokens are tiktoken's (tested against tiktoken and
/// rustbpe on committed fixtures). The vocabulary is a callable `rank(std::string_view bytes) -> std::uint32_t`,
/// returning `bpe_no_rank` for bytes that are not a token: a hash map for a large vocabulary, a `static_map` or
/// `perfect_map` built by the compiler for a small one (then encoding is `constexpr` end to end). In tiktoken's
/// formats a token's rank is its id.
///
/// \snippet ml/bpe_demo.cpp bpe
///
/// **Relationships.** `result.hpp` (the errors), `containers/perfect_map.hpp` (a vocabulary built at compile
/// time). Splitting text into pieces, training a vocabulary, and reading tokenizer files belong to the libraries
/// above core. Group: \ref core.
///
/// **Implementations.** One.
///
/// **Guarantees.** `constexpr` when `rank` is. No allocation: the caller's output and scratch spans. Complexity:
/// O(n²) rank lookups for a piece of n bytes in the worst case, as tiktoken; pieces are short. Pure: the same
/// piece and vocabulary give the same tokens on any thread.
///
/// **Errors.** `bpe_error::output_too_small` (no slot for a piece that is one token, or fewer than `piece.size()`
/// slots, the most tokens a piece can give, for one that is not),
/// `scratch_too_small` (fewer than `bpe_scratch_size(piece.size())` parts), `unknown_bytes` (a single byte is not a
/// token: the vocabulary is not byte-level; `out` may then be partly written). The size checks come first, so on
/// those `out` is untouched.
///
/// **Performance.** `benchmarks/ml/bpe_benchmark.cpp`: against tiktoken's algorithm written out by hand with
/// the same lookup, about 20% faster (no allocation per piece). Against tiktoken and rustbpe themselves, on
/// 12.3 MB of Python source (2.8 million pieces), one thread, Release `-O3 -march=native`, Apple clang 17, Xeon
/// W-3245, 2026-11-11, with a PCRE2 split and an open-addressing vocabulary around it: cl100k, 9.2 million
/// tokens/s against tiktoken 0.14's 2.3 million (from Python); a 32,768-token vocabulary trained by rustbpe,
/// 11.0 million against tiktoken's 2.7 million and rustbpe 0.1's 0.9 million. Every token agreed with
/// tiktoken's. The merge alone is 19 and 26 million tokens/s; the split is the other half.
///
/// **Tests and demos.** `tests/ml/bpe_test.cpp` (tiktoken's and rustbpe's tokens on a committed fixture,
/// `tests/fixtures/ml/bpe_fixture.txt`, generated by `scripts/generate_bpe_fixture.py`), `demos/ml/bpe_demo.cpp`.
///
/// **Dependencies.** `<concepts>`, `<cstddef>`, `<cstdint>`, `<span>`, `<string_view>`, `snicholls/core/result.hpp`.
///
/// **Known issues.** A piece is at most 2^32 - 1 bytes.
///
/// **Status.** Experimental, new in 0.6.0.

#ifndef snicholls_core_ml_bpe_hpp
#define snicholls_core_ml_bpe_hpp

#include <snicholls/core/result.hpp>

#include <concepts>
#include <cstddef>
#include <cstdint>
#include <span>
#include <string_view>

namespace snicholls::ml
{

/// \brief The rank a vocabulary lookup returns for bytes that are not a token.
inline constexpr std::uint32_t bpe_no_rank = 0xffffffffu;

/// \brief Why `bpe_encode_piece` or `bpe_decode` failed.
/// \ingroup core
enum class bpe_error
{
    output_too_small,    ///< The output span is shorter than the piece (or than the decoded bytes).
    scratch_too_small,   ///< The scratch span is shorter than `bpe_scratch_size(piece.size())`.
    unknown_bytes,       ///< A byte (or, decoding, a token id) is not in the vocabulary.
};

/// \brief One part of a piece during merging: where it starts, and the rank of it merged with the next part.
/// \ingroup core
struct bpe_part
{
    std::uint32_t start;   ///< The offset of the part in the piece.
    std::uint32_t rank;    ///< The rank of this part and the next together, or `bpe_no_rank`.
};

/// \brief A vocabulary lookup: bytes to their rank, or `bpe_no_rank`.
/// \ingroup core
template <typename F>
concept bpe_vocabulary = requires(F& f, std::string_view bytes) {
    { f(bytes) } -> std::convertible_to<std::uint32_t>;
};

/// \brief The scratch parts `bpe_encode_piece` needs for a piece of `n` bytes: `n + 1`.
/// \param n The piece's length.
/// \return The number of `bpe_part`s.
constexpr std::size_t bpe_scratch_size(std::size_t n) noexcept { return n + 1; }

/// \brief Encodes one piece (a match of the tokenizer's split pattern) into tokens, as tiktoken does.
/// \tparam Rank A `bpe_vocabulary`.
/// \param piece The bytes of the piece.
/// \param rank The vocabulary: bytes to rank, `bpe_no_rank` if not a token.
/// \param out Receives the tokens: `piece.size()` slots always suffice; one does when the piece is a token.
/// \param scratch Working space: at least `bpe_scratch_size(piece.size())` parts.
/// \return The number of tokens written, or why not.
template <bpe_vocabulary Rank>
constexpr result<std::size_t, bpe_error> bpe_encode_piece(std::string_view piece, Rank&& rank, std::span<std::uint32_t> out,
                                                          std::span<bpe_part> scratch)
{
    const std::size_t n = piece.size();
    if (n == 0)
        return ok(std::size_t{0});
    if (out.empty())
        return err(bpe_error::output_too_small);
    if (const std::uint32_t whole = rank(piece); whole != bpe_no_rank) {   // the common case: one token, no scratch
        out[0] = whole;
        return ok(std::size_t{1});
    }
    if (out.size() < n)
        return err(bpe_error::output_too_small);
    if (scratch.size() < bpe_scratch_size(n))
        return err(bpe_error::scratch_too_small);

    // parts[i] = (start of part i, rank of parts i and i+1 merged); the last two are sentinels
    std::size_t len = n + 1;
    bpe_part* parts = scratch.data();
    std::uint32_t min_rank = bpe_no_rank;
    std::size_t min_at = 0;
    for (std::size_t i = 0; i + 1 < n; ++i) {
        const std::uint32_t r = rank(piece.substr(i, 2));
        if (r < min_rank) {
            min_rank = r;
            min_at = i;
        }
        parts[i] = {static_cast<std::uint32_t>(i), r};
    }
    parts[n - 1] = {static_cast<std::uint32_t>(n - 1), bpe_no_rank};
    parts[n] = {static_cast<std::uint32_t>(n), bpe_no_rank};

    // The rank of parts i and i+1 merged with i+2: the bytes from part i to part i+3
    const auto rank_after_merge = [&](std::size_t i) -> std::uint32_t {
        if (i + 3 < len)
            return rank(piece.substr(parts[i].start, parts[i + 3].start - parts[i].start));
        return bpe_no_rank;
    };
    while (min_rank != bpe_no_rank) {
        const std::size_t i = min_at;
        if (i > 0)
            parts[i - 1].rank = rank_after_merge(i - 1);
        parts[i].rank = rank_after_merge(i);
        for (std::size_t k = i + 1; k + 1 < len; ++k)   // remove part i+1
            parts[k] = parts[k + 1];
        --len;
        min_rank = bpe_no_rank;
        for (std::size_t k = 0; k + 1 < len; ++k)
            if (parts[k].rank < min_rank) {
                min_rank = parts[k].rank;
                min_at = k;
            }
    }

    // The tokens are the ranks of the parts. Only a part of one byte can be missing (a merged part is a token by
    // construction), and then the vocabulary is not byte-level.
    const std::size_t count = len - 1;
    for (std::size_t k = 0; k < count; ++k) {
        out[k] = rank(piece.substr(parts[k].start, parts[k + 1].start - parts[k].start));
        if (out[k] == bpe_no_rank)
            return err(bpe_error::unknown_bytes);
    }
    return ok(count);
}

/// \brief Decodes tokens to bytes: the concatenation of each token's bytes.
/// \tparam Bytes A callable `bytes(std::uint32_t id) -> std::string_view`, empty for an unknown id.
/// \param tokens The tokens.
/// \param bytes The vocabulary's reverse lookup.
/// \param out Receives the bytes.
/// \return The number of bytes written, or `unknown_bytes` / `output_too_small`; `out` may be partly written.
template <typename Bytes>
    requires requires(Bytes& b, std::uint32_t id) {
        { b(id) } -> std::convertible_to<std::string_view>;
    }
constexpr result<std::size_t, bpe_error> bpe_decode(std::span<const std::uint32_t> tokens, Bytes&& bytes, std::span<char> out)
{
    std::size_t at = 0;
    for (const std::uint32_t id : tokens) {
        const std::string_view b = bytes(id);
        if (b.empty())
            return err(bpe_error::unknown_bytes);
        if (out.size() - at < b.size())
            return err(bpe_error::output_too_small);
        for (const char c : b)
            out[at++] = c;
    }
    return ok(at);
}

} // namespace snicholls::ml

#endif // snicholls_core_ml_bpe_hpp
