/// \brief A Unicode general category (UnicodeData.txt field 2), in the order the generated tables index.
/// \ingroup core
enum class unicode_category : std::uint8_t
{
    unassigned,              ///< Cn: not assigned (also any value past U+10FFFF).
    uppercase_letter,        ///< Lu.
    lowercase_letter,        ///< Ll.
    titlecase_letter,        ///< Lt.
    modifier_letter,         ///< Lm.
    other_letter,            ///< Lo.
    nonspacing_mark,         ///< Mn.
    spacing_mark,            ///< Mc.
    enclosing_mark,          ///< Me.
    decimal_number,          ///< Nd.
    letter_number,           ///< Nl.
    other_number,            ///< No.
    connector_punctuation,   ///< Pc.
    dash_punctuation,        ///< Pd.
    open_punctuation,        ///< Ps.
    close_punctuation,       ///< Pe.
    initial_punctuation,     ///< Pi.
    final_punctuation,       ///< Pf.
    other_punctuation,       ///< Po.
    math_symbol,             ///< Sm.
    currency_symbol,         ///< Sc.
    modifier_symbol,         ///< Sk.
    other_symbol,            ///< So.
    space_separator,         ///< Zs.
    line_separator,          ///< Zl.
    paragraph_separator,     ///< Zp.
    control,                 ///< Cc.
    format,                  ///< Cf.
    surrogate,               ///< Cs.
    private_use,             ///< Co.
};

/// \brief U+FFFD REPLACEMENT CHARACTER, what an invalid byte decodes as.
inline constexpr char32_t replacement_character = U'�';

/// \brief The most code points `decompose` writes for one code point (U+1E08 and friends need 3; 4 is the bound).
inline constexpr std::size_t max_decomposition = 4;

/// \brief One decoded code point: its value, the bytes it took, and whether those bytes were valid UTF-8.
/// \ingroup core
struct utf8_decoded
{
    char32_t code_point;   ///< The code point, or U+FFFD for an invalid byte.
    std::uint8_t length;   ///< The bytes consumed: 1 to 4, and 1 for an invalid byte; 0 only at the end of the text.
    bool valid;            ///< False when the byte at the offset does not start a well-formed sequence.
};

/// \brief Decodes the code point at byte `at` of `text`, strictly (Unicode Table 3-7).
/// \param text UTF-8 bytes.
/// \param at A byte offset; at or past the end gives `{0, 0, false}`.
/// \return The code point and its length; an invalid byte is one byte of U+FFFD with `valid == false`.
constexpr utf8_decoded decode_utf8(std::string_view text, std::size_t at) noexcept
{
    if (at >= text.size())
        return {0, 0, false};
    const auto byte = [&](std::size_t i) -> std::uint32_t { return static_cast<unsigned char>(text[at + i]); };
    const std::size_t left = text.size() - at;
    const std::uint32_t b0 = byte(0);
    constexpr utf8_decoded bad{replacement_character, 1, false};
    if (b0 < 0x80)
        return {b0, 1, true};
    const auto cont = [&](std::size_t i, std::uint32_t lo = 0x80, std::uint32_t hi = 0xBF) {
        return i < left && byte(i) >= lo && byte(i) <= hi;
    };
    if (b0 >= 0xC2 && b0 <= 0xDF)
        return cont(1) ? utf8_decoded{((b0 & 0x1F) << 6) | (byte(1) & 0x3F), 2, true} : bad;
    if (b0 >= 0xE0 && b0 <= 0xEF) {
        const std::uint32_t lo = b0 == 0xE0 ? 0xA0 : 0x80, hi = b0 == 0xED ? 0x9F : 0xBF;
        if (!cont(1, lo, hi) || !cont(2))
            return bad;
        return {((b0 & 0x0F) << 12) | ((byte(1) & 0x3F) << 6) | (byte(2) & 0x3F), 3, true};
    }
    if (b0 >= 0xF0 && b0 <= 0xF4) {
        const std::uint32_t lo = b0 == 0xF0 ? 0x90 : 0x80, hi = b0 == 0xF4 ? 0x8F : 0xBF;
        if (!cont(1, lo, hi) || !cont(2) || !cont(3))
            return bad;
        return {((b0 & 0x07) << 18) | ((byte(1) & 0x3F) << 12) | ((byte(2) & 0x3F) << 6) | (byte(3) & 0x3F), 4, true};
    }
    return bad;
}

/// \brief The UTF-8 length of a code point: 1 to 4 (a surrogate or a value past U+10FFFF counts as U+FFFD's 3).
/// \param cp The code point.
/// \return Its encoded length in bytes.
constexpr std::size_t utf8_length(char32_t cp) noexcept
{
    if (cp < 0x80)
        return 1;
    if (cp < 0x800)
        return 2;
    if (cp < 0x10000 || cp > 0x10FFFF)
        return 3;
    return 4;
}

/// \brief Encodes a code point as UTF-8; a surrogate or a value past U+10FFFF is written as U+FFFD.
/// \param cp The code point.
/// \param out At least `utf8_length(cp)` bytes.
/// \return The bytes written: 1 to 4.
constexpr std::size_t encode_utf8(char32_t cp, char* out) noexcept
{
    if ((cp >= 0xD800 && cp <= 0xDFFF) || cp > 0x10FFFF)
        cp = replacement_character;
    if (cp < 0x80) {
        out[0] = static_cast<char>(cp);
        return 1;
    }
    if (cp < 0x800) {
        out[0] = static_cast<char>(0xC0 | (cp >> 6));
        out[1] = static_cast<char>(0x80 | (cp & 0x3F));
        return 2;
    }
    if (cp < 0x10000) {
        out[0] = static_cast<char>(0xE0 | (cp >> 12));
        out[1] = static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
        out[2] = static_cast<char>(0x80 | (cp & 0x3F));
        return 3;
    }
    out[0] = static_cast<char>(0xF0 | (cp >> 18));
    out[1] = static_cast<char>(0x80 | ((cp >> 12) & 0x3F));
    out[2] = static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
    out[3] = static_cast<char>(0x80 | (cp & 0x3F));
    return 4;
}

/// \brief Whether text is well-formed UTF-8 throughout.
/// \param text Any bytes.
/// \return True when every byte belongs to a valid sequence.
constexpr bool is_valid_utf8(std::string_view text) noexcept
{
    for (std::size_t i = 0; i < text.size();) {
        const utf8_decoded d = decode_utf8(text, i);
        if (!d.valid)
            return false;
        i += d.length;
    }
    return true;
}

/// \brief Copies text with every invalid byte replaced by U+FFFD, as llama.cpp and Hugging Face's lossy decoding
/// treat it.
/// \param text Any bytes.
/// \param out At least `3 * text.size()` bytes (asserted).
/// \return The bytes written.
constexpr std::size_t replace_invalid_utf8(std::string_view text, std::span<char> out) noexcept
{
    std::size_t at = 0;
    for (std::size_t i = 0; i < text.size();) {
        const utf8_decoded d = decode_utf8(text, i);
        if (d.valid)
            for (std::size_t k = 0; k < d.length; ++k)
                out[at++] = text[i + k];
        else
            at += encode_utf8(replacement_character, out.data() + at);
        i += d.length;
    }
    return at;
}

namespace detail::unicode
{
    // The run of the generated category table that holds cp: the last run starting at or before it
    constexpr unicode_category category_search(char32_t cp) noexcept
    {
        const auto& t = snicholls::detail::unicode_tables::categories;
        std::size_t lo = 0, hi = std::size(t);   // the answer is in [lo, hi)
        while (hi - lo > 1) {
            const std::size_t mid = lo + (hi - lo) / 2;
            if ((t[mid] >> 5) <= cp)
                lo = mid;
            else
                hi = mid;
        }
        return static_cast<unicode_category>(t[lo] & 31u);
    }

    inline constexpr std::array<unicode_category, 128> ascii_categories = [] {
        std::array<unicode_category, 128> a{};
        for (char32_t c = 0; c < 128; ++c)
            a[c] = category_search(c);
        return a;
    }();
} // namespace detail::unicode

/// \brief The general category of a code point (Unicode 16.0).
/// \param cp The code point; a value past U+10FFFF is `unassigned`.
/// \return Its category.
constexpr unicode_category category(char32_t cp) noexcept
{
    if (cp < 128)
        return detail::unicode::ascii_categories[cp];
    if (cp > 0x10FFFF)
        return unicode_category::unassigned;
    return detail::unicode::category_search(cp);
}

/// \brief Whether a category is a letter, `\p{L}` (Lu, Ll, Lt, Lm, Lo).
/// \param c A category.
/// \return Whether it is in the class.
constexpr bool is_letter(unicode_category c) noexcept
{
    return c >= unicode_category::uppercase_letter && c <= unicode_category::other_letter;
}
/// \brief Whether a category is a mark, `\p{M}` (Mn, Mc, Me).
/// \param c A category.
/// \return Whether it is in the class.
constexpr bool is_mark(unicode_category c) noexcept
{
    return c >= unicode_category::nonspacing_mark && c <= unicode_category::enclosing_mark;
}
/// \brief Whether a category is a number, `\p{N}` (Nd, Nl, No).
/// \param c A category.
/// \return Whether it is in the class.
constexpr bool is_number(unicode_category c) noexcept
{
    return c >= unicode_category::decimal_number && c <= unicode_category::other_number;
}
/// \brief Whether a category is punctuation, `\p{P}` (Pc, Pd, Ps, Pe, Pi, Pf, Po).
/// \param c A category.
/// \return Whether it is in the class.
constexpr bool is_punctuation(unicode_category c) noexcept
{
    return c >= unicode_category::connector_punctuation && c <= unicode_category::other_punctuation;
}
/// \brief Whether a category is a symbol, `\p{S}` (Sm, Sc, Sk, So).
/// \param c A category.
/// \return Whether it is in the class.
constexpr bool is_symbol(unicode_category c) noexcept
{
    return c >= unicode_category::math_symbol && c <= unicode_category::other_symbol;
}
/// \brief Whether a category is a separator, `\p{Z}` (Zs, Zl, Zp).
/// \param c A category.
/// \return Whether it is in the class.
constexpr bool is_separator(unicode_category c) noexcept
{
    return c >= unicode_category::space_separator && c <= unicode_category::paragraph_separator;
}
/// \brief Whether a category is "other", `\p{C}` (Cc, Cf, Cs, Co, Cn).
/// \param c A category.
/// \return Whether it is in the class.
constexpr bool is_other(unicode_category c) noexcept
{
    return c == unicode_category::unassigned || c >= unicode_category::control;
}
/// \brief GPT-4o's upper class `[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]`.
/// \param c A category.
/// \return Whether it is in the class.
constexpr bool is_uppercase_class(unicode_category c) noexcept
{
    return (is_letter(c) && c != unicode_category::lowercase_letter) || is_mark(c);
}
/// \brief GPT-4o's lower class `[\p{Ll}\p{Lm}\p{Lo}\p{M}]`.
/// \param c A category.
/// \return Whether it is in the class.
constexpr bool is_lowercase_class(unicode_category c) noexcept
{
    return c == unicode_category::lowercase_letter || c == unicode_category::modifier_letter ||
           c == unicode_category::other_letter || is_mark(c);
}

/// \brief The White_Space property (PropList.txt): what `\s` matches in the Rust and Python regex engines.
/// \param cp The code point.
/// \return Whether it is whitespace.
constexpr bool is_whitespace(char32_t cp) noexcept
{
    if (cp < 0x80)
        return cp == 0x20 || (cp >= 0x09 && cp <= 0x0D);
    return cp == 0x85 || cp == 0xA0 || cp == 0x1680 || (cp >= 0x2000 && cp <= 0x200A) || cp == 0x2028 ||
           cp == 0x2029 || cp == 0x202F || cp == 0x205F || cp == 0x3000;
}

/// \brief The simple lowercase mapping (UnicodeData.txt field 13).
/// \param cp The code point.
/// \return Its lowercase, or `cp` when it has none.
constexpr char32_t to_lower(char32_t cp) noexcept
{
    if (cp < 128)
        return cp >= 'A' && cp <= 'Z' ? cp + 32 : cp;
    const auto& r = snicholls::detail::unicode_tables::lowercase_runs;
    std::size_t lo = 0, hi = std::size(r) / 4;   // the last run starting at or before cp is in [lo, hi)
    if (cp < static_cast<char32_t>(r[0]))
        return cp;
    while (hi - lo > 1) {
        const std::size_t mid = lo + (hi - lo) / 2;
        if (static_cast<char32_t>(r[4 * mid]) <= cp)
            lo = mid;
        else
            hi = mid;
    }
    const auto first = static_cast<char32_t>(r[4 * lo]);
    const auto count = static_cast<char32_t>(r[4 * lo + 1]), stride = static_cast<char32_t>(r[4 * lo + 2]);
    const char32_t offset = cp - first;
    if (offset % stride != 0 || offset / stride >= count)
        return cp;
    return static_cast<char32_t>(static_cast<std::int32_t>(cp) + r[4 * lo + 3]);
}

/// \brief The canonical combining class of a code point (0 for a starter).
/// \param cp The code point.
/// \return Its class, 0 to 240.
constexpr std::uint8_t combining_class(char32_t cp) noexcept
{
    const auto& t = snicholls::detail::unicode_tables::combining_classes;
    std::size_t lo = 0, hi = std::size(t);
    while (lo < hi) {   // the first range whose last code point is at or after cp
        const std::size_t mid = lo + (hi - lo) / 2;
        if (((t[mid] >> 8) & 0x1FFFFF) < cp)
            lo = mid + 1;
        else
            hi = mid;
    }
    if (lo < std::size(t) && (t[lo] >> 29) <= cp)
        return static_cast<std::uint8_t>(t[lo] & 0xFF);
    return 0;
}

namespace detail::unicode
{
    // The direct canonical decomposition of cp: 0, 1 or 2 code points (Hangul excluded)
    constexpr std::size_t decompose_once(char32_t cp, char32_t& a, char32_t& b) noexcept
    {
        const auto& t = snicholls::detail::unicode_tables::decompositions;
        std::size_t lo = 0, hi = std::size(t);
        while (lo < hi) {
            const std::size_t mid = lo + (hi - lo) / 2;
            if ((t[mid] >> 42) < cp)
                lo = mid + 1;
            else
                hi = mid;
        }
        if (lo == std::size(t) || (t[lo] >> 42) != cp)
            return 0;
        a = static_cast<char32_t>((t[lo] >> 21) & 0x1FFFFF);
        b = static_cast<char32_t>(t[lo] & 0x1FFFFF);
        return b == 0 ? 1 : 2;
    }
} // namespace detail::unicode

/// \brief The full canonical decomposition of a code point, Hangul syllables included, unordered.
/// \param cp The code point.
/// \param out Receives the decomposition: `max_decomposition` slots always suffice.
/// \return The code points written: 1 when `cp` has no decomposition (then `out[0] == cp`).
///
/// The decomposition is in the order of the table's mappings; NFD is these code points with each run of
/// non-starters sorted stably by `combining_class`.
constexpr std::size_t decompose(char32_t cp, std::span<char32_t, max_decomposition> out) noexcept
{
    if (cp >= 0xAC00 && cp < 0xAC00 + 11172) {   // Hangul, UAX #15
        const char32_t s = cp - 0xAC00;
        out[0] = 0x1100 + s / 588;
        out[1] = 0x1161 + (s % 588) / 28;
        if (s % 28 == 0)
            return 2;
        out[2] = 0x11A7 + s % 28;
        return 3;
    }
    // Expand the first code point until it has no mapping; every second code point of a canonical mapping is
    // itself fully decomposed, so only the first needs expanding again.
    std::size_t n = 1;
    out[0] = cp;
    for (;;) {
        char32_t a = 0, b = 0;
        const std::size_t k = detail::unicode::decompose_once(out[0], a, b);
        if (k == 0 || (k == 2 && n == max_decomposition))
            return n;
        if (k == 2) {
            for (std::size_t i = n; i > 1; --i)
                out[i] = out[i - 1];
            out[1] = b;
            ++n;
        }
        out[0] = a;
    }
}

