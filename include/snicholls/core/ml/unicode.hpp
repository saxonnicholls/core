/// \file
/// \brief `snicholls::ml` Unicode for tokenizers: strict UTF-8 decoding and encoding, every code point's general category, White_Space, the simple lowercase mapping and canonical decomposition, all `constexpr` from tables the compiler holds.
/// \ingroup core
///
/// **Overview.** The character facts a tokenizer's split pattern and normaliser ask about, without a regex
/// engine, a locale or ICU:
///
/// - `decode_utf8(text, at)`: the code point at a byte offset and its length, strictly (no overlong forms, no
///   surrogates, nothing past U+10FFFF). A byte that does not start a valid sequence decodes as one byte of U+FFFD
///   with `valid == false`, as llama.cpp's tokenizers treat it, so a tokenizer never stalls on bad input.
///   `encode_utf8(cp, out)` is the inverse; `is_valid_utf8` and `replace_invalid_utf8` check and repair whole texts.
/// - `category(cp)`: the general category (`unicode_category`, Unicode 16.0), and the group tests the split
///   patterns use: `is_letter`, `is_mark`, `is_number`, `is_punctuation`, `is_symbol`, `is_separator`,
///   `is_other`, and `is_uppercase_class` / `is_lowercase_class` (GPT-4o's `[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]` and
///   `[\p{Ll}\p{Lm}\p{Lo}\p{M}]`). `is_whitespace(cp)` is the White_Space property, which is what `\s` means in
///   the Rust and Python regex engines the tokenizers were written for.
/// - `to_lower(cp)`: the simple lowercase mapping of UnicodeData.txt.
/// - `decompose(cp, out)`: the full canonical decomposition, Hangul syllables included, and `combining_class(cp)`.
///   Together they are NFD; with the marks dropped, BERT's `strip_accents`.
///
/// \snippet ml/unicode_demo.cpp unicode
///
/// **Relationships.** The tables are `detail/unicode_tables.hpp`, generated by `scripts/generate_unicode_tables.py`
/// from the committed extract `scripts/data/ucd-16.0.0.txt` of UnicodeData.txt and cross-checked against
/// llama.cpp's own tables (the CTest `generated.unicode_tables_up_to_date`). Used by `ml/pretokenize.hpp`,
/// `ml/wordpiece.hpp`, `ml/unigram.hpp`, `ml/sentencepiece.hpp` and `ml/bpe_merges.hpp`. Group: \ref core.
///
/// **Implementations.** One. Categories are 4,099 runs searched by bisection, with a 128-entry table built at
/// compile time in front for ASCII; the lowercase mapping is 187 runs; decompositions 2,081 sorted entries.
///
/// **Guarantees.** Every function is `constexpr` and `noexcept`, allocates nothing and reads only its arguments
/// and the tables. Complexity: O(1) for ASCII, O(log n) otherwise (12 steps for a category).
///
/// **Errors.** None: invalid UTF-8 is a value (`valid == false`), a code point past U+10FFFF is `unassigned`.
/// `decompose` writes at most `max_decomposition` code points and returns how many.
///
/// **Performance.** `benchmarks/ml/unicode_benchmark.cpp`: decoding and classifying text against a hand loop that
/// decodes the same way and looks up the same table. See BENCHMARKS.md.
///
/// **Tests and demos.** `tests/ml/unicode_test.cpp` (decoding against the UTF-8 rules of Unicode Table 3-7, every
/// category run against the extract, decompositions against Hangul's algorithm and spot values), `demos/ml/unicode_demo.cpp`.
///
/// **Dependencies.** `<array>`, `<cstddef>`, `<cstdint>`, `<span>`, `<string_view>`, `detail/unicode_tables.hpp`
/// (about 90 KB of integer tables; including it costs a few milliseconds of compile time).
///
/// **Known issues.** The tables are Unicode 16.0; llama.cpp's category flags predate it, so for the 5,185 code points
/// first assigned in 16.0 the two disagree (llama.cpp has them unassigned). Lowercasing is the simple mapping, one
/// code point to one; the only unconditional full mapping that differs, U+0130 to "i̇", is the caller's to apply
/// (`ml/wordpiece.hpp` does, as Hugging Face's BERT normaliser does).
///
/// **Status.** Experimental, new in 0.17.0.

