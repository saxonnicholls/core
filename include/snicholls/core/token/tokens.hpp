/// \file
/// \brief The major tokens as types: `snicholls::token::ethereum::USDC`, `token::bsc::USDT`, `token::tron::USDT`, ...
/// \ingroup core
///
/// **Overview.** The handful of tokens nearly every product touches, compiled in: chain, contract address,
/// decimals and symbol, each a `basic_token` checked by the compiler (EIP-55 or base58check address, decimals, code),
/// and who stands behind it on that chain: `issuer()`, `kind()` (an `issuance`) and `source()`, the first-party page
/// that lists the address.
///
/// | Chain (`snicholls::token::`) | Token | Kind | Issuer on this chain |
/// |---|---|---|---|
/// | `ethereum` (1) | `USDT` | native | Tether |
/// | | `USDC`, `EURC` | native | Circle |
/// | | `DAI` | native | Sky (formerly MakerDAO) |
/// | | `WETH` | wrapped | WETH9, the canonical ownerless contract |
/// | | `WBTC` | wrapped | BitGo, custodian, governed by the WBTC DAO |
/// | `optimism` (10) | `USDT` | bridged | the OP Mainnet standard bridge, not Tether |
/// | | `USDC` | native | Circle |
/// | `bsc` (56) | `USDT`, `USDC` | pegged | Binance (Binance-Peg), not Tether or Circle; 18 decimals, not 6 |
/// | `polygon` (137) | `USDT0` | bridged | USDT0 (formerly Polygon PoS bridged USDT, same contract) |
/// | | `USDC` | native | Circle (not the bridged USDC.e) |
/// | `base` (8453) | `USDT` | bridged | the Base standard bridge, not Tether |
/// | | `USDC` | native | Circle |
/// | `arbitrum` (42161) | `USDT0` | bridged | USDT0 |
/// | | `USDC` | native | Circle |
/// | `avalanche` (43114) | `USDT` | native | Tether |
/// | | `USDC` | native | Circle |
/// | `tron` (728126428) | `USDT` | native | Tether |
///
/// `snicholls::token::all` is every one of them as a `type_list`, to seed a run-time registry or to run a check over
/// all. Each code is `SYMBOL:chainid` (`USDC:1`, `USDC:56`), so one symbol on two chains is two assets: `USDC:56` is
/// Binance's token, not Circle's, and the type says so (`token::bsc::USDC::kind() == issuance::pegged`). Grouping a
/// symbol across chains is the run-time registry's job, not core's. Everything else, the long tail, is data in
/// servers' run-time registry, behind `token_interface`.
///
/// **Naming.** A namespace per chain, named as the chain type is (`token::base::USDC` beside `chain::base`), and the
/// token by its symbol in capitals, as the currency types are (`currency::AUD`). Chosen over flat names
/// (`USDC_base`) because the chain reads first, as an address book does; `using namespace snicholls::token::base;`
/// gives a product on one chain the bare symbols; and the namespaces list a chain's tokens in the documentation.
///
/// \snippet token/tokens_demo.cpp tokens
///
/// **Sources.** Generated by `scripts/generate_tokens.py` from `scripts/data/tokens/issuers.json` alone. Every
/// address comes from a first-party page: the issuer's (Circle's and Tether's address lists, Sky's chainlog), or for a
/// bridged, pegged or wrapped token the bridge operator's (USDT0's deployments, Optimism's Superchain token list), the
/// pegging party's (Binance's) or the canonical contract's (ethereum.org for WETH, the WBTC DAO's repositories). Each
/// is copied as the page writes it; decimals come from the page or, where it gives none, from a block explorer or the
/// contract itself, and `source` in the data says which. `name()` is the contract's own `name()`. The access date is
/// `detail::token_data_accessed`. Some addresses are corroborated by a second first-party page, which the generator
/// compares.
///
/// **Relationships.** `token/basic_token.hpp`, `concepts/token.hpp`, `interfaces/token.hpp`, `chain/chains.hpp`,
/// `money/asset.hpp`, `meta/type_list.hpp`. Group: \ref core.
///
/// **Implementations.** One generated struct per token, deriving from `basic_token` and adding `name()`, `issuer()`,
/// `kind()` and `source()`.
///
/// **Guarantees.** constexpr, `noexcept`, no state. Every address is case-exact in its chain's canonical form.
///
/// **Errors.** None at run time; a wrong address in the data would be a compile error.
///
/// **Performance.** Nothing at run time. Not applicable.
///
/// **Tests and demos.** `tests/token/tokens_test.cpp` checks every type's address (case-exact), decimals, kind,
/// chain and code against `tests/fixtures/tokens/tokens.txt`, which the generator writes from the committed data, and
/// runs `check_token` over each; the CTest `generated.tokens_up_to_date` fails if the header or the fixture drifts
/// from the data. No network at build or test time, except the opt-in CTest `external.tokens_cross_check`
/// (`-DSNICHOLLS_CORE_NETWORK_TESTS=ON` or `SNICHOLLS_CORE_NETWORK_TESTS=1`; skipped otherwise or offline), which is
/// `scripts/generate_tokens.py --cross-check`: it downloads Uniswap Labs' default token list, a pinned npm release,
/// into a temporary directory and compares every address and decimals value; `--latest` compares with the newest
/// release. Nothing from that list (GPL-3.0) is committed. Demo: `demos/token/tokens_demo.cpp`.
///
/// **Dependencies.** `chain/chains.hpp`, `meta/type_list.hpp`, `token/basic_token.hpp`,
/// `detail/token_table.hpp` (generated).
///
/// **Known issues.**
/// - Tether's symbol on Arbitrum and Polygon is `USDT0`: those contracts are the USDT0 project's, and Polygon's former
///   PoS-bridged USDT became USDT0 at the same address. The contract writes it `USD₮0` on Arbitrum.
/// - Optimism's and Base's `USDT` are the standard bridges' tokens; USDT0 has its own contract on Optimism, which is
///   not included.
/// - TRON's USDC is not included: Circle discontinued it.
/// - The names are the contracts' own and differ between chains (`TetherToken` on Avalanche).
///
/// **Status.** New in 0.23.0.

