/// \file
/// \brief ISO 3166-1: every country as a type (`snicholls::country::AU`) and as a constexpr table, from Unicode CLDR,
/// with its currencies from SIX and its E.164 calling code from core's own table.
/// \ingroup core
///
/// **Overview.** Country codes change only when ISO 3166 is revised, so they are compiled in. Each country is a type
/// in `snicholls::country`, named by its alpha-2 code in capitals (`AU`, `GB`, `DO`; lowercase would make `do` and
/// `in` keywords). Each type has `static constexpr` member functions:
/// - `alpha2()`, `alpha3()`, `numeric()`;
/// - `name()`, CLDR's English name ("Australia", "Hong Kong SAR China");
/// - `currencies()`, the ISO 4217 codes in use, from SIX's list one with the funds left out, sorted: exactly the
///   inverse of the currencies' `countries()` (`money/iso4217.hpp`);
/// - `calling_code()`, the E.164 country calling code, read from `detail/e164_country_codes.hpp` (the table
///   `phone_number.hpp` uses), 0 where none is assigned (Antarctica, Bouvet Island).
///
/// Every type models `country_like` (`concepts/country.hpp`). The same data is a sorted table for codes that arrive
/// at run time: `find_country("AU")`, `find_country("AUS")`, `find_country(36)`. The literal `"AU"_country` is
/// checked by the compiler.
///
/// The table is generated by `scripts/generate_iso3166.py` from the subset of CLDR committed under
/// `scripts/data/cldr/` (its release is `iso3166_cldr_version`, its licence `scripts/data/cldr/LICENSE`). ISO 3166-1
/// is CLDR's regular regions with an alpha-3 and a numeric code below 900: not the exceptional reservations (AC, CP,
/// DG, EA, IC, TA) nor the user-assigned XK.
///
/// \snippet country_demo.cpp country
///
/// **Relationships.** `concepts/country.hpp`, `interfaces/country.hpp`, `money/iso4217.hpp`, `phone_number.hpp`.
/// Group: \ref core.
///
/// **Implementations.** One generated type per country, and the generated table.
///
/// **Guarantees.**
/// - constexpr, `noexcept`, no allocation.
/// - The table is sorted by alpha-2; alpha-3 and numeric codes are unique, and are searched through sorted
///   permutations.
///
/// **Errors.** `find_country` returns `nullptr` for an unknown code; `"ZZ"_country` is a compile error.
///
/// **Performance.** Binary search over 249 rows, at compile time where the code is a constant. Not benchmarked.
///
/// **Tests and demos.** `tests/country_test.cpp` (checked against pycountry, babel and phonenumbers through
/// `tests/fixtures/countries/countries.tsv`, CTest `generated.country_fixtures_up_to_date`; the table against its
/// sources by `generated.iso3166_up_to_date`), `demos/country_demo.cpp`.
///
/// **Dependencies.** `<cstddef>`, `<cstdint>`, `<span>`, `<string_view>`, `detail/iso3166_table.hpp` (249 types and
/// rows: heavier than it looks, so include it only where needed).
///
/// **Known issues.**
/// - A platform macro of two capitals hides its country type: `<windows.h>` defines `IN`, Objective-C's `<objc/objc.h>`
///   defines `NO`. Use `find_country("IN")` there, or include this header first and `#undef` the macro.
/// - Names are CLDR's English names, not ISO's short names ("Palestinian Territories", "U.S. Outlying Islands").
/// - Currencies are SIX's: where CLDR 47 lags (Bulgaria's euro of 2026) or adds unofficial ones (GBP in South
///   Georgia), the test lists the differences from babel.
///
/// **Status.** New in 0.23.0.

#ifndef snicholls_core_country_hpp
#define snicholls_core_country_hpp

#include <snicholls/core/detail/iso3166_table.hpp>

#include <cstddef>
#include <cstdint>
#include <span>
#include <string_view>

namespace snicholls {

    namespace detail {
        // Indices, not pointers: GCC cannot compare a pointer into a constexpr table with nullptr in a constant
        // expression. A binary search over the rows in the order `at` gives (at(i) is the row at position i);
        // iso3166_rows.size() when the key is not there.
        template <typename Key, typename At, typename Get>
        constexpr std::size_t iso3166_search(Key key, At at, Get get) noexcept
        {
            std::size_t lo = 0, hi = iso3166_rows.size();
            while (lo < hi) {
                const std::size_t mid = lo + (hi - lo) / 2;
                const Key k = get(iso3166_rows[at(mid)]);
                if (k == key)
                    return at(mid);
                if (k < key)
                    lo = mid + 1;
                else
                    hi = mid;
            }
            return iso3166_rows.size();
        }

        constexpr std::size_t iso3166_index(std::string_view code) noexcept
        {
            if (code.size() == 2)
                return iso3166_search(code, [](std::size_t i) { return i; }, [](const iso3166_row& r) { return r.alpha2; });
            if (code.size() == 3)
                return iso3166_search(code, [](std::size_t i) -> std::size_t { return iso3166_by_alpha3[i]; },
                                      [](const iso3166_row& r) { return r.alpha3; });
            return iso3166_rows.size();
        }

        constexpr std::size_t iso3166_index(std::uint16_t numeric) noexcept
        {
            return iso3166_search(numeric, [](std::size_t i) -> std::size_t { return iso3166_by_numeric[i]; },
                                  [](const iso3166_row& r) { return r.numeric; });
        }
    } // namespace detail

    /// \brief One ISO 3166-1 country: `alpha2`, `alpha3`, `numeric`, `name` (CLDR's English name), `currencies` (ISO
    /// 4217 codes, sorted) and `calling_code` (E.164, 0 where none is assigned).
    using country_entry = detail::iso3166_row;

    /// \brief The Unicode CLDR release the table was generated from.
    inline constexpr std::string_view iso3166_cldr_version = detail::iso3166_cldr_version;

    /// \brief Every country, sorted by alpha-2.
    /// \return The table.
    [[nodiscard]] constexpr std::span<const country_entry> iso3166_entries() noexcept { return detail::iso3166_rows; }

    /// \brief The country with this alpha-2 or alpha-3 code.
    /// \param code Two or three capitals.
    /// \return The entry, or `nullptr` if ISO 3166-1 has no such code.
    [[nodiscard]] constexpr const country_entry* find_country(std::string_view code) noexcept
    {
        const std::size_t i = detail::iso3166_index(code);
        return i < detail::iso3166_rows.size() ? &detail::iso3166_rows[i] : nullptr;
    }

    /// \brief The country with this numeric code.
    /// \param numeric The numeric code (36 for Australia).
    /// \return The entry, or `nullptr`.
    [[nodiscard]] constexpr const country_entry* find_country(std::uint16_t numeric) noexcept
    {
        const std::size_t i = detail::iso3166_index(numeric);
        return i < detail::iso3166_rows.size() ? &detail::iso3166_rows[i] : nullptr;
    }

    namespace literals {
        /// \brief `"AU"_country` or `"AUS"_country`: a country's entry, checked by the compiler.
        /// \param s The alpha-2 or alpha-3 code.
        /// \param n Its length.
        /// \return The entry; an unknown code is a compile error.
        consteval country_entry operator""_country(const char* s, std::size_t n)
        {
            const std::size_t i = detail::iso3166_index(std::string_view{s, n});
            if (i >= detail::iso3166_rows.size())
                throw "snicholls::operator\"\"_country: not an ISO 3166-1 alpha-2 or alpha-3 code";   // a compile error
            return detail::iso3166_rows[i];
        }
    } // namespace literals

} // namespace snicholls

#endif // snicholls_core_country_hpp
