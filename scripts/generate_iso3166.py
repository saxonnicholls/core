#!/usr/bin/env python3
#
#  generate_iso3166.py
#  snicholls-core
#
#  Copyright 2010-2026 Saxon Herschel Nicholls
#
#  Writes include/snicholls/core/detail/iso3166_table.hpp: every ISO 3166-1 country as a type (struct AU, struct GB,
#  ...) in snicholls::country and as a row of a sorted constexpr table, from:
#
#      scripts/data/cldr/territories.tsv    alpha-2, alpha-3, numeric and the English name, extracted from Unicode
#                                           CLDR by scripts/extract_cldr.py
#      scripts/data/iso4217/                the currencies in use, from SIX's list one (funds left out), read through
#                                           scripts/generate_iso4217.py, so a country's currencies() and a
#                                           currency's countries() are each other's inverse
#      scripts/data/e164/country_codes.txt  the E.164 calling codes; the table refers to the rows of
#                                           detail/e164_country_codes.hpp by index, so no calling code is written twice
#
#      scripts/generate_iso3166.py            # writes the header
#      scripts/generate_iso3166.py --check    # exits 1 if the committed header differs (CTest generated.iso3166_up_to_date)
#
#  The standard library only. Never edit the generated header by hand.
#

import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CLDR = ROOT / "scripts" / "data" / "cldr" / "territories.tsv"
E164 = ROOT / "scripts" / "data" / "e164" / "country_codes.txt"
OUT = ROOT / "include" / "snicholls" / "core" / "detail" / "iso3166_table.hpp"


def iso4217():
    """scripts/generate_iso4217.py as a module: the one reader of SIX's lists."""
    sys.dont_write_bytecode = True   # no __pycache__ in scripts/
    spec = importlib.util.spec_from_file_location("generate_iso4217", ROOT / "scripts" / "generate_iso4217.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def tsv(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            yield line.split("\t")


def read():
    """(CLDR version, [row]) sorted by alpha-2; each row's `e164` is its index in country_codes[], or None."""
    version = CLDR.read_text(encoding="utf-8").splitlines()[0].split()[3]   # "# Unicode CLDR 47 (...)"
    e164 = {}
    for index, (code, _trunk, regions) in enumerate(tsv(E164)):
        for region in regions.split(" "):
            e164.setdefault(region, (index, int(code)))
    in_use = iso4217().country_currencies()
    rows = []
    for a2, a3, numeric, name in tsv(CLDR):
        rows.append({"alpha2": a2, "alpha3": a3, "numeric": int(numeric), "name": name,
                     "currencies": in_use.get(a2, []), "e164": e164.get(a2)})
    rows.sort(key=lambda r: r["alpha2"])
    if len({r["alpha3"] for r in rows}) != len(rows) or len({r["numeric"] for r in rows}) != len(rows):
        raise SystemExit("iso3166: alpha-3 and numeric codes must be unique")
    if len(rows) > 255:
        raise SystemExit("iso3166: the permutations are std::uint8_t; widen them")
    return version, rows


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(version, rows):
    out = []
    w = out.append
    w("//")
    w("//  iso3166_table.hpp")
    w("//  snicholls-core")
    w("//")
    w("//  Copyright 2010-2026 Saxon Herschel Nicholls")
    w("//")
    w(f"//  GENERATED by scripts/generate_iso3166.py from Unicode CLDR {version} (scripts/data/cldr/, the Unicode licence),")
    w("//  SIX's ISO 4217 list one and core's E.164 table. Never edit by hand: CTest generated.iso3166_up_to_date.")
    w("//")
    w("")
    w("#ifndef snicholls_core_detail_iso3166_table_hpp")
    w("#define snicholls_core_detail_iso3166_table_hpp")
    w("")
    w("#include <snicholls/core/detail/e164_country_codes.hpp>")
    w("")
    w("#include <array>")
    w("#include <cstdint>")
    w("#include <span>")
    w("#include <string_view>")
    w("")
    w("namespace snicholls::detail {")
    w("")
    flat, offsets = [], {}
    for r in rows:
        offsets[r["alpha2"]] = len(flat)
        flat.extend(r["currencies"])
    w("    // The currencies in use in every country (SIX's list one, funds left out), each run sorted; rows point into it.")
    w(f"    inline constexpr std::array<std::string_view, {len(flat)}> iso3166_currencies{{{{")
    for i in range(0, len(flat), 12):
        w("        " + " ".join(f'"{c}",' for c in flat[i:i + 12]))
    w("    }};")
    w("")
    w("    // One row of the ISO 3166-1 table.")
    w("    struct iso3166_row {")
    w("        std::string_view alpha2;   // two capitals")
    w("        std::string_view alpha3;   // three capitals")
    w("        std::uint16_t numeric;     // 1 to 899")
    w("        std::string_view name;     // CLDR's English name")
    w("        std::span<const std::string_view> currencies;   // ISO 4217 codes in use (SIX list one, no funds), sorted")
    w("        std::uint16_t calling_code;   // the E.164 country calling code, 0 where none is assigned")
    w("    };")
    w("")
    w(f'    inline constexpr std::string_view iso3166_cldr_version = "{version}";')
    w("")
    w(f"    // Every country, sorted by alpha-2: {len(rows)} rows.")
    w(f"    inline constexpr std::array<iso3166_row, {len(rows)}> iso3166_rows{{{{")
    for r in rows:
        span = (f'{{iso3166_currencies.data() + {offsets[r["alpha2"]]}, {len(r["currencies"])}}}'
                if r["currencies"] else "{}")
        call = f'e164::country_codes[{r["e164"][0]}].code' if r["e164"] else "0"
        w(f'        {{"{r["alpha2"]}", "{r["alpha3"]}", {r["numeric"]}, {cstr(r["name"])}, {span}, {call}}},')
    w("    }};")
    w("")
    for key, what in (("alpha3", "alpha-3"), ("numeric", "numeric code")):
        order = sorted(range(len(rows)), key=lambda i: rows[i][key])
        w(f"    // The rows in order of {what}, for a binary search.")
        w(f"    inline constexpr std::array<std::uint8_t, {len(rows)}> iso3166_by_{key}{{{{")
        for i in range(0, len(order), 24):
            w("        " + " ".join(f"{x}," for x in order[i:i + 24]))
        w("    }};")
        w("")
    w("} // namespace snicholls::detail")
    w("")
    w("namespace snicholls::country {")
    w("")
    w("    // One type per country, named by its alpha-2 code; each models snicholls::country_like.")
    for index, r in enumerate(rows):
        a2 = r["alpha2"]
        n = len(r["currencies"])
        w(f"    /// \\brief ISO 3166-1 {a2}: {r['name']}, {r['alpha3']}, numeric {r['numeric']:03d}.")
        w(f"    struct {a2} {{")
        w(f"        /// \\brief The alpha-2 code.")
        w(f"        /// \\return `\"{a2}\"`.")
        w(f'        static constexpr std::string_view alpha2() noexcept {{ return "{a2}"; }}')
        w(f"        /// \\brief The alpha-3 code.")
        w(f"        /// \\return `\"{r['alpha3']}\"`.")
        w(f'        static constexpr std::string_view alpha3() noexcept {{ return "{r["alpha3"]}"; }}')
        w(f"        /// \\brief The numeric code.")
        w(f"        /// \\return {r['numeric']}.")
        w(f"        static constexpr std::uint16_t numeric() noexcept {{ return {r['numeric']}; }}")
        w(f"        /// \\brief The English name, as CLDR gives it.")
        w(f"        /// \\return The name.")
        w(f"        static constexpr std::string_view name() noexcept {{ return {cstr(r['name'])}; }}")
        w(f"        /// \\brief The ISO 4217 currencies in use, from SIX's list one (funds left out), sorted.")
        w(f"        /// \\return {n} code{'' if n == 1 else 's'}" + (f": {', '.join(r['currencies'])}." if n else "."))
        w(f"        static constexpr std::span<const std::string_view> currencies() noexcept {{ return detail::iso3166_rows[{index}].currencies; }}")
        w(f"        /// \\brief The E.164 country calling code, from core's E.164 table.")
        if r["e164"]:
            w(f"        /// \\return {r['e164'][1]}.")
            w(f"        static constexpr std::uint16_t calling_code() noexcept {{ return detail::e164::country_codes[{r['e164'][0]}].code; }}")
        else:
            w(f"        /// \\return 0: none is assigned.")
            w(f"        static constexpr std::uint16_t calling_code() noexcept {{ return 0; }}")
        w("    };")
    w("")
    w("} // namespace snicholls::country")
    w("")
    w("#endif // snicholls_core_detail_iso3166_table_hpp")
    w("")
    return "\n".join(out)


def main(argv):
    version, rows = read()
    text = render(version, rows)
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"iso3166: {OUT.relative_to(ROOT)} is not what scripts/generate_iso3166.py writes; regenerate it",
                  file=sys.stderr)
            return 1
        print(f"iso3166: up to date ({len(rows)} countries, CLDR {version})")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"iso3166: wrote {OUT.relative_to(ROOT)} ({len(rows)} countries, CLDR {version})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
