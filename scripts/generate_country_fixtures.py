"""Generate the oracle fixtures for country.hpp and the CLDR metadata of money/iso4217.hpp:

    tests/fixtures/countries/countries.tsv   every ISO 3166-1 country
    tests/fixtures/money/currencies.tsv      every ISO 4217 code of SIX's lists

Every expected value comes from a library independent of core's generators, pinned below, never from core:

- pycountry (its own copy of ISO 3166-1): alpha-2, alpha-3, numeric; and the countries using each currency (and so
  the currencies of each country, funds left out), by matching the entity names of SIX's list one to pycountry's
  names (the curated scripts/data/iso4217/entities.tsv is never read here);
- babel (Unicode CLDR, the release VERSIONS records): the English names, the currencies in use on SNAPSHOT_DATE, the
  fractions (digits, rounding, cash digits, cash rounding) and the root locale's symbols;
- phonenumbers (libphonenumber's metadata): each country's calling code.

    ./scripts/generate_country_fixtures.py           rewrite the fixtures (needs the pinned packages)
    ./scripts/generate_country_fixtures.py --check   exit 1 if the committed fixtures differ from this script's output;
                                                     skipped (exit 0) unless every pinned package is installed

Format: tab-separated, '#' starts a comment.
    countries.tsv:  alpha2 alpha3 numeric calling_code six_currencies cldr_currencies name
                    (currencies sorted, space-separated, '-' for none; six_ from SIX through pycountry, cldr_ from
                    babel, which differ where one source lags the other)
    currencies.tsv: code digits rounding cash_digits cash_rounding root_symbol countries(sorted alpha-2)
                    (the four fractions are babel's, which fills CLDR's defaults in; countries only for list one,
                    '-' for none)
"""
import datetime
import pathlib
import re
import sys
import unicodedata
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
VERSIONS = {"babel": "2.18.0", "pycountry": "26.2.16", "phonenumbers": "9.0.44"}
SNAPSHOT_DATE = datetime.date(2026, 11, 23)
SIX = ROOT / "scripts" / "data" / "iso4217"
COUNTRIES = ROOT / "tests" / "fixtures" / "countries" / "countries.tsv"
CURRENCIES = ROOT / "tests" / "fixtures" / "money" / "currencies.tsv"


def packages():
    """(babel, pycountry, phonenumbers) at the pinned versions, or None."""
    try:
        import babel
        import phonenumbers
        import pycountry
        from importlib.metadata import version
    except ImportError:
        return None
    if version("babel") != VERSIONS["babel"] or version("pycountry") != VERSIONS["pycountry"] \
            or phonenumbers.__version__ != VERSIONS["phonenumbers"]:
        return None
    return babel, pycountry, phonenumbers


def fold(name):
    """Capitals without accents (TÜRKİYE and Türkiye agree), with a plain apostrophe."""
    plain = unicodedata.normalize("NFKD", name.replace("’", "'"))
    return "".join(c for c in plain if not unicodedata.combining(c)).upper()


def spellings(entity):
    """The ways an ISO 3166 short name in SIX's capitals may be written in pycountry."""
    s = fold(entity).replace(" (THE)", "").replace("[", "(").replace("]", ")")
    out = [s]
    m = re.fullmatch(r"(.*) \((.*)\)", s)
    if m:
        place, qualifier = m.groups()
        bare = qualifier.removeprefix("THE ")
        out += [f"{bare} {place}", f"{place}, {bare}", f"{place}, {qualifier}", place,
                f"{bare.replace(' OF THE', ' OF')} THE {place}"]
    return out


def entity_alpha2(pycountry, entity):
    names = {}
    for c in pycountry.countries:
        for n in (c.name, getattr(c, "official_name", None), getattr(c, "common_name", None)):
            if n:
                names[fold(n)] = c.alpha_2
                names.setdefault(fold(re.sub(r" \(.*\)$", "", n)), c.alpha_2)   # Holy See (Vatican City State)
    for s in spellings(entity):
        if s in names:
            return names[s]
    return None


def header(what):
    pins = ", ".join(f"{k} {v}" for k, v in VERSIONS.items())
    return (f"# {what}\n# GENERATED by scripts/generate_country_fixtures.py from {pins} (CLDR as babel carries it),\n"
            f"# currencies in use on {SNAPSHOT_DATE}; never core's own output, never edited by hand.\n")


def six(pycountry):
    """({currency: alpha-2 set}, {alpha-2: currency set without funds}) from SIX's list one through pycountry."""
    by_currency, by_country = {}, {}
    for e in ET.parse(SIX / "list-one.xml").getroot().iter("CcyNtry"):
        code = (e.findtext("Ccy") or "").strip()
        if not code:
            continue
        a2 = entity_alpha2(pycountry, (e.findtext("CtryNm") or "").strip())
        by_currency.setdefault(code, set())
        if a2:
            by_currency[code].add(a2)
            if e.find("CcyNm").get("IsFund") != "true":
                by_country.setdefault(a2, set()).add(code)
    return by_currency, by_country


def countries_text(babel, pycountry, phonenumbers):
    from babel import Locale
    from babel.numbers import get_territory_currencies
    en = Locale("en").territories
    by_country = six(pycountry)[1]
    lines = [header("ISO 3166-1 countries"),
             "# alpha2\talpha3\tnumeric\tcalling_code\tsix_currencies\tcldr_currencies\tname\n"]
    for c in sorted(pycountry.countries, key=lambda c: c.alpha_2):
        cldr = sorted(get_territory_currencies(c.alpha_2, start_date=SNAPSHOT_DATE, tender=True))
        call = phonenumbers.country_code_for_region(c.alpha_2)
        lines.append("\t".join([c.alpha_2, c.alpha_3, c.numeric, str(call),
                                " ".join(sorted(by_country.get(c.alpha_2, ()))) or "-", " ".join(cldr) or "-",
                                en[c.alpha_2]]) + "\n")
    return "".join(lines)


def currencies_text(babel, pycountry):
    from babel.core import get_global
    from babel.numbers import get_currency_symbol
    fractions = get_global("currency_fractions")
    three = ET.parse(SIX / "list-three.xml").getroot()
    countries = six(pycountry)[0]
    codes = sorted(set(countries) | {(e.findtext("Ccy") or "").strip() for e in three.iter("HstrcCcyNtry")} - {""})
    lines = [header("ISO 4217 codes: CLDR's fractions and root symbols, SIX's countries"),
             "# code\tdigits\trounding\tcash_digits\tcash_rounding\troot_symbol\tcountries\n"]
    for code in codes:
        f = fractions.get(code, fractions["DEFAULT"])
        lines.append("\t".join([code, *map(str, f), get_currency_symbol(code, "root"),
                                " ".join(sorted(countries.get(code, ()))) or "-"]) + "\n")
    return "".join(lines)


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit("usage: generate_country_fixtures.py [--check]")
    pkgs = packages()
    if pkgs is None:
        pins = " ".join(f"{k}=={v}" for k, v in VERSIONS.items())
        if check:
            print(f"country fixtures: skipped, {pins} are not all installed")
            return 0
        sys.exit(f"generate_country_fixtures: pip install {pins}")
    babel, pycountry, phonenumbers = pkgs
    out = {COUNTRIES: countries_text(babel, pycountry, phonenumbers), CURRENCIES: currencies_text(babel, pycountry)}
    if check:
        stale = [p for p, text in out.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"country fixtures: {p.relative_to(ROOT)} is not what this script computes; regenerate it",
                  file=sys.stderr)
        if not stale:
            print("country fixtures: up to date")
        return 1 if stale else 0
    for p, text in out.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"country fixtures: wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
