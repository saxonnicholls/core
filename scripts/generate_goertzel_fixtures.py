"""Generate the oracle fixture for include/snicholls/core/signal/goertzel.hpp (tests/fixtures/signal/goertzel.txt).

Every expected value comes from numpy, pinned to NUMPY_VERSION below, never from core: `numpy.fft.fft` for the
integer bins, and the transform at a frequency between bins (the generalised Goertzel algorithm's answer) as
`numpy.sum(x * w * numpy.exp(-2j * numpy.pi * f / fs * numpy.arange(n)))`, with the periodic windows taken from
numpy's own (`numpy.hanning(n + 1)[:-1]`, `numpy.kaiser(n + 1, beta)[:-1]`). The signals are numpy's PCG64 normal
draws (fixed seed) rounded to float32, so a float, double and long double detector all read the same samples, with
tones added for the DTMF case.

    python3 -I scripts/generate_goertzel_fixtures.py           rewrite the fixture (needs numpy==2.2.5)
    python3 -I scripts/generate_goertzel_fixtures.py --check   exit 1 if the committed fixture differs from this
                                                               script's output; skipped (exit 0) without numpy 2.2.5

numpy's transcendental functions may differ in the last bit between machines (SIMD paths), so --check compares the
numbers to a relative 1e-12 of each record's scale and the rest of the text exactly.

Format: tab-separated, '#' starts a comment.
    signal  <name>  <n>  x_0 ... x_(n-1)
    fft     <name>  re_0 im_0 ... re_(n-1) im_(n-1)              every bin of numpy.fft.fft(x)
    dtft    <name>  <window>  <frequency>  <sample rate>  re  im   the windowed sum at that frequency
Windows: rect, hann, kaiser8.6 (beta 8.6), all periodic.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NUMPY_VERSION = "2.2.5"
OUT = ROOT / "tests" / "fixtures" / "signal" / "goertzel.txt"

DTMF = [697.0, 770.0, 852.0, 941.0, 1209.0, 1336.0, 1477.0, 1633.0]


def render(np):
    rng = np.random.default_rng(20261124)
    lines = ["# generated by scripts/generate_goertzel_fixtures.py with numpy %s; do not edit" % np.__version__,
             "# signal / fft / dtft records: see the script's docstring"]

    def g(v):
        return "%.17g" % float(v)

    def window(name, n):
        if name == "rect":
            return np.ones(n)
        if name == "hann":
            return np.hanning(n + 1)[:-1]
        if name == "kaiser8.6":
            return np.kaiser(n + 1, 8.6)[:-1]
        raise ValueError(name)

    def signal(name, x):
        lines.append("\t".join(["signal", name, str(len(x))] + [g(v) for v in x]))

    def fft(name, x):
        X = np.fft.fft(x)
        lines.append("\t".join(["fft", name] + [g(v) for z in X for v in (z.real, z.imag)]))

    def dtft(name, x, wname, f, fs):
        n = len(x)
        z = np.sum(x * window(wname, n) * np.exp(-2j * np.pi * f / fs * np.arange(n)))
        lines.append("\t".join(["dtft", name, wname, g(f), g(fs), g(z.real), g(z.imag)]))

    def noise(n):
        return rng.standard_normal(n).astype(np.float32).astype(np.float64)

    # Random blocks, every integer bin: a power of two, an odd length, a prime and a mixed-radix length.
    for n in (64, 63, 101, 200):
        name = "noise%d" % n
        x = noise(n)
        signal(name, x)
        fft(name, x)
        # Frequencies between bins (sample rate n, so the frequency is the fractional bin), every window.
        for f in (0.37, 3.5, n / 4 + 0.25, n / 2 - 0.4, n - 1.7):
            for wname in ("rect", "hann", "kaiser8.6"):
                dtft(name, x, wname, f, float(n))

    # DTMF at 8 kHz over 205 samples (no tone is on a bin): digit 5 (770 Hz + 1336 Hz) in noise.
    n, fs = 205, 8000.0
    t = np.arange(n) / fs
    x = (np.sin(2 * np.pi * 770.0 * t) + 0.8 * np.sin(2 * np.pi * 1336.0 * t + 0.3) + 0.1 * rng.standard_normal(n))
    x = x.astype(np.float32).astype(np.float64)
    signal("dtmf5", x)
    for f in DTMF:
        for wname in ("rect", "hann"):
            dtft("dtmf5", x, wname, f, fs)
    return "\n".join(lines) + "\n"


def same(a, b):
    """The two fixtures agree: identical text but for numbers, which agree to 1e-12 of their record's scale."""
    la, lb = a.splitlines(), b.splitlines()
    if len(la) != len(lb):
        return False
    for x, y in zip(la, lb):
        if x.startswith("#") or y.startswith("#"):
            if x.split(" with numpy")[0] != y.split(" with numpy")[0]:
                return False
            continue
        fx, fy = x.split("\t"), y.split("\t")
        if len(fx) != len(fy):
            return False
        nums = []
        for u, v in zip(fx, fy):
            try:
                nums.append((float(u), float(v)))
            except ValueError:
                if u != v:
                    return False
        scale = max([1.0] + [abs(u) for u, _ in nums])
        if any(abs(u - v) > 1e-12 * scale for u, v in nums):
            return False
    return True


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit("usage: generate_goertzel_fixtures.py [--check]")
    try:
        import numpy as np
    except ImportError:
        np = None
    if np is None or np.__version__ != NUMPY_VERSION:
        if check:
            print(f"goertzel fixtures: skipped, numpy=={NUMPY_VERSION} is not installed")
            return 0
        sys.exit(f"generate_goertzel_fixtures: needs numpy=={NUMPY_VERSION}")
    text = render(np)
    if check:
        ok = OUT.exists() and same(OUT.read_text(encoding="utf-8"), text)
        print("goertzel fixtures: " + ("up to date" if ok else "DIFFER"))
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count(chr(10)) - 2} records")
    return 0


if __name__ == "__main__":
    sys.exit(main())
