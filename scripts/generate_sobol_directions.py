#  Copyright 2010-2026 Saxon Herschel Nicholls
#
#  Write include/snicholls/core/detail/sobol_directions.hpp from Joe and Kuo's published
#  direction numbers (https://web.maths.unsw.edu.au/~fkuo/sobol/new-joe-kuo-6.21201):
#
#      curl -O https://web.maths.unsw.edu.au/~fkuo/sobol/new-joe-kuo-6.21201
#      scripts/generate_sobol_directions.py new-joe-kuo-6.21201 [dimensions, default 1024]
#
#  Never edit the generated header by hand. The table's invariants (each m_k odd and below
#  2^k, rows in order) are checked here and again by tests/detail/sobol_directions_test.cpp.
#

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "include/snicholls/core/detail/sobol_directions.hpp"


def main() -> None:
    if len(sys.argv) not in (2, 3):
        sys.exit("usage: scripts/generate_sobol_directions.py <new-joe-kuo-6.21201> [dimensions]")
    dimensions = int(sys.argv[2]) if len(sys.argv) == 3 else 1024
    lines = pathlib.Path(sys.argv[1]).read_text(encoding="ascii").splitlines()
    if lines[0].split() != ["d", "s", "a", "m_i"]:
        sys.exit("generate_sobol_directions: not a Joe-Kuo file (unexpected header)")
    degree, coefficients, offset, m = [], [], [], []
    for expected, line in zip(range(2, dimensions + 1), lines[1:]):
        fields = [int(x) for x in line.split()]
        d, s, a, ms = fields[0], fields[1], fields[2], fields[3:]
        if d != expected or len(ms) != s:
            sys.exit(f"generate_sobol_directions: malformed row for dimension {expected}: {line!r}")
        for k, mk in enumerate(ms, start=1):
            if mk % 2 == 0 or mk >= (1 << k):
                sys.exit(f"generate_sobol_directions: dimension {d}: m_{k} = {mk} is not odd and below 2^{k}")
        degree.append(s)
        coefficients.append(a)
        offset.append(len(m))
        m.extend(ms)
    if len(degree) != dimensions - 1:
        sys.exit(f"generate_sobol_directions: the file has fewer than {dimensions} dimensions")

    def table(values, per_line=24):
        rows = [", ".join(str(v) for v in values[i : i + per_line]) for i in range(0, len(values), per_line)]
        return ",\n        ".join(rows)

    OUT.write_text(f"""//
//  sobol_directions.hpp
//  snicholls-core
//
//  Copyright 2010-2026 Saxon Herschel Nicholls
//
//  GENERATED by scripts/generate_sobol_directions.py from Joe and Kuo's new-joe-kuo-6.21201
//  (https://web.maths.unsw.edu.au/~fkuo/sobol/), dimensions 2 to {dimensions}. Do not edit.
//  S. Joe and F. Y. Kuo, "Constructing Sobol sequences with better two-dimensional
//  projections", SIAM J. Sci. Comput. 30, 2635-2654 (2008).
//

#ifndef snicholls_core_detail_sobol_directions_hpp
#define snicholls_core_detail_sobol_directions_hpp

#include <cstddef>
#include <cstdint>

namespace snicholls::detail {{

    // The most dimensions the table holds; dimension 1 is implicit (every m_k = 1).
    inline constexpr std::size_t sobol_max_dimensions = {dimensions};

    // For dimension d (from 2), at index d - 2: the primitive polynomial's degree s and inner coefficients a,
    // and where its s initial direction numbers m_1 .. m_s start in sobol_m.
    inline constexpr std::uint8_t sobol_degree[{len(degree)}] = {{
        {table(degree)}}};

    inline constexpr std::uint32_t sobol_coefficients[{len(coefficients)}] = {{
        {table(coefficients, 16)}}};

    inline constexpr std::uint16_t sobol_m_offset[{len(offset)}] = {{
        {table(offset, 16)}}};

    inline constexpr std::uint16_t sobol_m[{len(m)}] = {{
        {table(m, 20)}}};

}} // namespace snicholls::detail

#endif /* snicholls_core_detail_sobol_directions_hpp */
""")
    print(f"generate_sobol_directions: wrote {OUT.relative_to(ROOT)} ({dimensions} dimensions, {len(m)} direction numbers)", file=sys.stderr)


if __name__ == "__main__":
    main()
