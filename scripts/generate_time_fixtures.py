"""Generate the portability fixtures for include/snicholls/core/time/ (tests/fixtures/time/*.tsv).

The expected values come from Python's own date arithmetic (datetime.date / timedelta, the proleptic Gregorian
calendar) and exact integer arithmetic (a value as numerator / denominator, floored with Python's `//` on
unbounded integers), never from core. The same committed files are read by the same
tests on macOS, every `make ubuntu` configuration and CI, so a platform that disagrees with Python - or with another
platform - fails there. A divergence is a bug in core: fix it and add the case here.

    ./scripts/generate_time_fixtures.py           rewrite the fixtures (commit the result)
    ./scripts/generate_time_fixtures.py --check   exit 1 if the committed fixtures differ from this script's output

Files (tab-separated, one case per line, '#' starts a comment):

    rfc3339_format.tsv   resolution ticks precision text
        utc<resolution> holding `ticks` written by to_chars at `precision` digits ('-' = the resolution's own)
    rfc3339_parse.tsv    resolution policy text expected
        parse_utc<resolution>(text, strict|lenient options) -> ticks, or invalid_argument / result_out_of_range
    unix_text.tsv        unit resolution policy text expected
        parse_unix<unit, resolution>(text) -> ticks (exact floor) or an error
    timespec.tsv         tv_sec tv_nsec resolution ticks
        utc<resolution>::from_timespec <-> to_timespec, flooring toward the past
    civil.tsv            days year month day weekday last_day_of_month
        days since 1970-01-01 <-> civil date; weekday 0 = Sunday
    business_days.tsv    op a b expected
        add a n -> days; between a b -> count; prev/next a weekday -> days
"""
import datetime
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "fixtures" / "time"
EPOCH = datetime.date(1970, 1, 1)
NS = {"s": 10**9, "ms": 10**6, "us": 10**3, "ns": 1}        # nanoseconds per tick
DIGITS = {"s": 0, "ms": 3, "us": 6, "ns": 9}
INT64_MIN, INT64_MAX = -(2**63), 2**63 - 1

HEADER = [
    "# GENERATED by scripts/generate_time_fixtures.py from Python's datetime and exact integer arithmetic - do not edit by hand.",
]


class Lcg:
    """A fixed 64-bit LCG (Knuth MMIX), so the 'random' cases never depend on Python's random module."""

    def __init__(self, seed):
        self.x = seed

    def next(self):
        self.x = (self.x * 6364136223846793005 + 1442695040888963407) % 2**64
        return self.x

    def below(self, n):
        return self.next() % n


def civil(days):
    return EPOCH + datetime.timedelta(days=days)


def days_of(d):
    return (d - EPOCH).days


def rfc3339(ns_total, digits):
    """RFC 3339 text of an instant given in (possibly huge) nanoseconds, floored to `digits` fraction digits."""
    secs, sub = divmod(ns_total, 10**9)           # floor: sub in [0, 1e9)
    days, sod = divmod(secs, 86400)
    d = civil(days)
    text = "%04d-%02d-%02dT%02d:%02d:%02d" % (d.year, d.month, d.day, sod // 3600, sod // 60 % 60, sod % 60)
    if digits > 0:
        text += "." + ("%09d" % sub)[:digits]
    return text + "Z"


# ---- instants ---------------------------------------------------------------------------------------------------

def ns_of(y, mo, d, h=0, mi=0, s=0, sub_ns=0):
    return (days_of(datetime.date(y, mo, d)) * 86400 + h * 3600 + mi * 60 + s) * 10**9 + sub_ns


NAMED = [
    ns_of(1970, 1, 1),                                   # the epoch
    -1,                                                  # one ns before it
    -999_999_999, -1_000_000_000, -1_000_000_001,        # around -1 s
    1,
    ns_of(1969, 12, 31, 23, 59, 59, 500_000_000),
    ns_of(2000, 2, 29, 12, 0, 0, 123_456_789),           # leap day of a 400-year leap year
    ns_of(2024, 2, 29, 23, 59, 59, 999_999_999),         # last ns of a leap day
    ns_of(2024, 3, 1),
    ns_of(1900, 2, 28, 23, 59, 59, 999_999_999),         # 1900 is not a leap year
    ns_of(1900, 3, 1),
    ns_of(2100, 2, 28, 23, 59, 59, 1),
    ns_of(2100, 3, 1, 0, 0, 0, 1),
    ns_of(1999, 12, 31, 23, 59, 59, 999_999_999),        # year boundaries
    ns_of(2000, 1, 1),
    ns_of(2025, 12, 31, 23, 59, 59, 999_000_000),
    ns_of(2026, 1, 1, 0, 0, 0, 1_000),
    ns_of(1677, 9, 21, 0, 12, 43, 145_224_192),          # utc<> minimum = INT64_MIN ns
    ns_of(2262, 4, 11, 23, 47, 16, 854_775_807),         # utc<> maximum = INT64_MAX ns
    ns_of(1700, 1, 1, 0, 0, 0, 1),
    ns_of(2262, 1, 1),
    ns_of(2024, 4, 30, 14, 23, 5, 123_456_789),
    ns_of(1969, 7, 20, 20, 17, 40),                      # pre-1970, whole seconds
    ns_of(1950, 6, 15, 6, 30, 0, 999_999_999),
    ns_of(1800, 12, 31, 23, 59, 59, 999_999_999),
]
assert NAMED[18] == INT64_MIN and NAMED[19] == INT64_MAX


def instants_ns():
    rng = Lcg(20261106)
    out = list(NAMED)
    for _ in range(120):
        out.append(INT64_MIN + rng.below(2**64))       # anywhere in utc<>'s range
    return out


# Beyond utc<>: the coarser resolutions reach every year RFC 3339 (and Python) can write, 0001..9999.
WIDE = [
    (ns_of(1, 1, 1), "0001-01-01 start"),
    (ns_of(9999, 12, 31, 23, 59, 59, 999_999_999), "9999-12-31 end"),
    (ns_of(1000, 3, 1, 1, 2, 3, 456_789_000), "1000-03-01"),
    (ns_of(1600, 2, 29, 23, 59, 59, 999_999_999), "1600 leap day"),
    (ns_of(3000, 12, 31, 12), "3000"),
    (ns_of(8888, 8, 8, 8, 8, 8, 888_888_888), "8888"),
    (ns_of(1, 3, 1, 0, 0, 0, 1_000_000), "0001-03-01"),
]


def gen_format():
    rows = []
    for ns in instants_ns():
        for res in ("s", "ms", "us", "ns"):
            ticks = ns // NS[res]
            rows.append((res, ticks, "-", rfc3339(ticks * NS[res], DIGITS[res])))
    for ns, _ in WIDE:
        for res in ("s", "ms", "us"):
            ticks = ns // NS[res]
            if INT64_MIN <= ticks <= INT64_MAX:
                rows.append((res, ticks, "-", rfc3339(ticks * NS[res], DIGITS[res])))
    # Every explicit precision 0..9 from every resolution: floored, or zero-padded.
    for ns in NAMED[:10] + NAMED[18:20]:
        for res in ("s", "ms", "us", "ns"):
            ticks = ns // NS[res]
            for p in range(10):
                rows.append((res, ticks, str(p), rfc3339(ticks * NS[res], p)))
    return ["\t".join(map(str, r)) for r in rows]


# ---- parsing ----------------------------------------------------------------------------------------------------

def floor_div(a, b):
    return a // b


def parse_expect(res, policy, y, mo, d, h, mi, s, frac, offset_min):
    """Expected parse_utc<res> of the given fields, by Python's calendar and exact arithmetic."""
    try:
        datetime.date(y, mo, d)
    except ValueError:
        return "invalid_argument"
    if h > 23 or mi > 59 or s > 60:
        return "invalid_argument"
    if abs(offset_min) >= 24 * 60:
        return "invalid_argument"
    leap = s == 60
    secs = days_of(datetime.date(y, mo, d)) * 86400 + h * 3600 + mi * 60 + (59 if leap else s) - offset_min * 60
    if leap and secs % 86400 != 86399:
        return "invalid_argument"                  # a leap second is only 23:59:60 UTC
    scale = 10 ** len(frac)
    if leap:
        if policy == "strict":
            return "result_out_of_range"
        ticks = (secs + 1) * 10**9 // NS[res] - 1   # exact: every resolution divides the second
    else:
        # value in ticks = (secs * scale + frac) * 1e9 / (scale * ns_per_tick), floored toward the past
        num = (secs * scale + (int(frac) if frac else 0)) * 10**9
        den = scale * NS[res]
        ticks = num // den
        if num % den != 0 and policy == "strict":
            return "result_out_of_range"
    if not INT64_MIN <= ticks <= INT64_MAX:
        return "result_out_of_range"
    return str(ticks)


def fmt_fields(y, mo, d, h, mi, s, frac, offset_min, sep="T", zulu="Z"):
    text = "%04d-%02d-%02d%s%02d:%02d:%02d" % (y, mo, d, sep, h, mi, s)
    if frac:
        text += "." + frac
    if offset_min is None:
        return text + zulu
    sign = "-" if offset_min < 0 else "+"
    m = abs(offset_min)
    return text + "%s%02d:%02d" % (sign, m // 60, m % 60)


def gen_parse():
    cases = [
        # (fields..., frac, offset minutes or None for Z)
        (2024, 4, 30, 14, 23, 5, "123456789", None),
        (2024, 4, 30, 10, 23, 5, "123456789", -240),
        (2024, 4, 30, 23, 23, 5, "1", 540),
        (2024, 2, 29, 0, 0, 0, "", None),
        (2023, 2, 29, 0, 0, 0, "", None),            # not a leap year
        (1900, 2, 29, 0, 0, 0, "", None),            # nor is 1900
        (2000, 2, 29, 0, 0, 0, "5", None),           # 2000 is
        (2025, 4, 31, 0, 0, 0, "", None),            # April has 30 days
        (2025, 13, 1, 0, 0, 0, "", None),
        (2025, 0, 1, 0, 0, 0, "", None),
        (2025, 1, 0, 0, 0, 0, "", None),
        (2025, 1, 1, 24, 0, 0, "", None),
        (2025, 1, 1, 23, 60, 0, "", None),
        (1969, 12, 31, 23, 59, 59, "999999999", None),
        (1969, 12, 31, 23, 59, 59, "5", None),
        (1969, 12, 31, 23, 59, 59, "0000000001", None),   # beyond ns: excess, but zero is not
        (1969, 12, 31, 23, 59, 59, "1234567891", None),
        (1970, 1, 1, 0, 0, 0, "0000000000000", None),     # many zero digits are fine
        (1677, 9, 21, 0, 12, 43, "145224192", None),      # utc<> minimum
        (1677, 9, 21, 0, 12, 43, "145224191", None),      # one ns below it
        (2262, 4, 11, 23, 47, 16, "854775807", None),     # utc<> maximum
        (2262, 4, 11, 23, 47, 16, "854775808", None),     # one ns above it
        (1, 1, 1, 0, 0, 0, "", None),
        (9999, 12, 31, 23, 59, 59, "999999999", None),
        (2016, 12, 31, 23, 59, 60, "", None),             # a real leap second
        (2016, 12, 31, 23, 59, 60, "5", None),
        (2016, 12, 31, 18, 59, 60, "", -300),             # the same, written in UTC-05:00
        (2016, 12, 31, 22, 59, 60, "", None),             # second 60 that is not 23:59 UTC
        (2024, 1, 1, 0, 0, 0, "", 23 * 60 + 59),
        (2024, 1, 1, 0, 0, 0, "", -(23 * 60 + 59)),
        (2024, 1, 1, 0, 30, 0, "", 30),
        (1600, 3, 1, 0, 0, 0, "12", None),
        (2400, 2, 29, 12, 0, 0, "", None),
    ]
    rng = Lcg(1106)
    for _ in range(80):
        y = 1 + rng.below(9999)
        mo = 1 + rng.below(12)
        d = 1 + rng.below(31)
        frac = "".join(str(rng.below(10)) for _ in range(rng.below(13)))
        off = None if rng.below(3) == 0 else rng.below(2 * 24 * 60 - 1) - (24 * 60 - 1)
        cases.append((y, mo, d, rng.below(24), rng.below(60), rng.below(60), frac, off))
    rows = []
    for y, mo, d, h, mi, s, frac, off in cases:
        text = fmt_fields(y, mo, d, h, mi, s, frac, off)
        for res in ("s", "ms", "us", "ns"):
            for policy in ("strict", "lenient"):
                rows.append((res, policy, text, parse_expect(res, policy, y, mo, d, h, mi, s, frac, off or 0)))
    # Syntax the strict parser refuses and the lenient one accepts, and syntax both refuse.
    for text, strict, lenient in [
        ("2024-04-30T14:23:05", "invalid_argument", parse_expect("ns", "lenient", 2024, 4, 30, 14, 23, 5, "", 0)),
        ("2024-04-30T14:23:05+0200", "invalid_argument",
         parse_expect("ns", "lenient", 2024, 4, 30, 14, 23, 5, "", 120)),
        ("2024-04-30t14:23:05z", parse_expect("ns", "strict", 2024, 4, 30, 14, 23, 5, "", 0),
         parse_expect("ns", "lenient", 2024, 4, 30, 14, 23, 5, "", 0)),
        ("2024-04-30 14:23:05Z", parse_expect("ns", "strict", 2024, 4, 30, 14, 23, 5, "", 0),
         parse_expect("ns", "lenient", 2024, 4, 30, 14, 23, 5, "", 0)),
        ("2024-04-30T14:23:05.Z", "invalid_argument", "invalid_argument"),
        ("2024-4-30T14:23:05Z", "invalid_argument", "invalid_argument"),
        ("2024-04-30T14:23Z", "invalid_argument", "invalid_argument"),
        ("+2024-04-30T14:23:05Z", "invalid_argument", "invalid_argument"),
        ("2024-04-30T14:23:05Zjunk", "invalid_argument", "invalid_argument"),
        ("2024-04-30T14:23:05+24:00", "invalid_argument", "invalid_argument"),
        ("2024-04-30T14:23:05+05:60", "invalid_argument", "invalid_argument"),
        ("", "invalid_argument", "invalid_argument"),
    ]:
        rows.append(("ns", "strict", text, strict))
        rows.append(("ns", "lenient", text, lenient))
    return ["\t".join(map(str, r)) for r in rows]


# ---- Unix numbers as text ---------------------------------------------------------------------------------------

def unix_expect(unit, res, policy, text):
    neg = text.startswith("-")
    body = text[1:] if neg else text
    whole = body.split(".")[0]
    if int(whole) > (2**63 if neg else 2**63 - 1):
        return "result_out_of_range"          # the integer part, in Unit, must fit int64
    frac = body.split(".")[1] if "." in body else ""
    scale = 10 ** len(frac)
    num = (int(whole) * scale + (int(frac) if frac else 0)) * (-1 if neg else 1) * NS[unit]   # ns x scale
    den = scale * NS[res]
    ticks = num // den                         # floor, toward the past
    if num % den != 0 and policy == "strict":
        return "result_out_of_range"
    if not INT64_MIN <= ticks <= INT64_MAX:
        return "result_out_of_range"
    return str(ticks)


def gen_unix():
    texts = ["0", "1", "-1", "1714486985", "1714486985123", "1714486985.123456789", "-1.5", "-0.5", "-0.000000001",
             "-0.0000000001", "0.0000000001", "-1714486985.123456789123", "1.999999999999", "-1.999999999999",
             "9223372036854775807", "-9223372036854775808", "9223372036854775808", "-9223372036854775809",
             "9223372036", "9223372037", "-9223372036", "-9223372037", "1.0", "-1.000000000", "0.5", "-86400.25",
             "253402300799", "-62135596800", "-62135596800.999"]
    rng = Lcg(42)
    for _ in range(24):
        whole = rng.below(10**12) * (1 if rng.below(2) else -1)
        frac = "".join(str(rng.below(10)) for _ in range(rng.below(12)))
        texts.append(("%d" % whole) + ("." + frac if frac else ""))
    rows = []
    for unit in ("s", "ms", "us", "ns"):
        for res in ("s", "ms", "us", "ns"):
            for policy in ("strict", "lenient"):
                for t in texts:
                    rows.append((unit, res, policy, t, unix_expect(unit, res, policy, t)))
    return ["\t".join(map(str, r)) for r in rows]


# ---- timespec ---------------------------------------------------------------------------------------------------

def gen_timespec():
    """(tv_sec, tv_nsec) <-> ticks: floor(tv_sec * 1e9 + tv_nsec, tick). Includes the timespec of utc<>::min(), whose
    whole second lies below what utc<> can hold (it failed to round-trip until 2026-11-09)."""
    rows = []
    for ns in instants_ns():
        sec, nsec = divmod(ns, 10**9)
        for res in ("s", "ms", "us", "ns"):
            rows.append((sec, nsec, res, ns // NS[res]))
    for ns, _ in WIDE:
        sec, nsec = divmod(ns, 10**9)
        for res in ("s", "ms", "us"):
            ticks = ns // NS[res]
            if INT64_MIN <= ticks <= INT64_MAX:
                rows.append((sec, nsec, res, ticks))
    return ["\t".join(map(str, r)) for r in rows]


# ---- civil dates ------------------------------------------------------------------------------------------------

def last_day(y, m):
    nxt = datetime.date(y + (m == 12), m % 12 + 1, 1) if not (y == 9999 and m == 12) else None
    return 31 if nxt is None else (nxt - datetime.timedelta(days=1)).day


def gen_civil():
    lo, hi = days_of(datetime.date(1, 1, 1)), days_of(datetime.date(9999, 12, 31))
    days = {lo, hi, 0, -1, 1, -4, -5, -6, -7, 59, 60, 365, -365, 10957, 11016, 11017, 19782, -25509, -25508,
            days_of(datetime.date(1600, 2, 29)), days_of(datetime.date(1700, 3, 1)), days_of(datetime.date(2100, 3, 1))}
    rng = Lcg(7)
    while len(days) < 400:
        days.add(lo + rng.below(hi - lo + 1))
    rows = []
    for z in sorted(days):
        d = civil(z)
        rows.append((z, d.year, d.month, d.day, d.isoweekday() % 7, last_day(d.year, d.month)))
    return ["\t".join(map(str, r)) for r in rows]


# ---- business days ----------------------------------------------------------------------------------------------

def is_bd(z):
    return civil(z).isoweekday() <= 5


def add_bd(z, n):
    step = 1 if n > 0 else -1
    for _ in range(abs(n)):
        z += step
        while not is_bd(z):
            z += step
    return z


def between(a, b):
    if a <= b:
        return sum(1 for z in range(a, b) if is_bd(z))
    return -between(b, a)


def gen_business():
    rng = Lcg(99)
    base = [0, -1, -2, -3, -4, -5, 1, 2, 3, 19782, 19783, 19784, 19785, 19786, 19787, 19788,
            days_of(datetime.date(1900, 1, 6)), days_of(datetime.date(2099, 12, 27))]
    rows = []
    for a in base + [rng.below(200000) - 100000 for _ in range(30)]:
        for n in (0, 1, -1, 2, -2, 4, -4, 5, -5, 6, -6, 7, -7, 13, -13, 250, -250, 1000):
            rows.append(("add", a, n, add_bd(a, n)))
        b = a + rng.below(800) - 400
        rows.append(("between", a, b, between(a, b)))
        rows.append(("between", b, a, between(b, a)))
        for wd in range(7):   # 0 = Sunday
            back = (civil(a).isoweekday() % 7 - wd) % 7 or 7
            ahead = (wd - civil(a).isoweekday() % 7) % 7 or 7
            rows.append(("prev", a, wd, a - back))
            rows.append(("next", a, wd, a + ahead))
    return ["\t".join(map(str, r)) for r in rows]


FILES = {
    "rfc3339_format.tsv": (gen_format, "resolution\tticks\tprecision\ttext"),
    "rfc3339_parse.tsv": (gen_parse, "resolution\tpolicy\ttext\texpected"),
    "unix_text.tsv": (gen_unix, "unit\tresolution\tpolicy\ttext\texpected"),
    "timespec.tsv": (gen_timespec, "tv_sec\ttv_nsec\tresolution\tticks"),
    "civil.tsv": (gen_civil, "days\tyear\tmonth\tday\tweekday\tlast_day_of_month"),
    "business_days.tsv": (gen_business, "op\ta\tb\texpected"),
}


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for name, (gen, columns) in FILES.items():
        text = "\n".join(HEADER + ["# " + columns] + gen()) + "\n"
        path = OUT / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print("generate_time_fixtures: out of date: " + ", ".join(stale) +
              " - run ./scripts/generate_time_fixtures.py and commit", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
