"""Generate the oracle fixture for include/snicholls/core/finance/returns.hpp (tests/fixtures/finance/returns.txt).

Every expected value comes from an implementation other than core's, never from core:
- `irr`: numpy-financial, pinned to NPF_VERSION below (`numpy_financial.irr`), and `numpy.roots` for the number of
  rates when there is more than one or none (numpy-financial picks one root where core reports `multiple_roots`);
- `xirr` and `mwr` (the annualised money-weighted return): Python's `decimal` at 60 digits, bisecting the net present
  value `sum c / (1 + r) ** (days / 365)` to 1e-40 (every case has one sign change, so one rate);
- `dietz` and `twr`: Python's `fractions`, exactly.
The cashflows are fixed cases and draws from Python's `random` with a fixed seed, in whole minor units.

    python3 -I scripts/generate_returns_fixtures.py           rewrite the fixture (needs numpy-financial==1.0.0)
    python3 -I scripts/generate_returns_fixtures.py --check   exit 1 if the committed fixture differs from this
                                                              script's output; skipped (exit 0) without it

numpy's eigenvalue solver may differ in the last bits between machines, so --check compares numbers to a relative
1e-12 and the rest of the text exactly.

Format: tab-separated, '#' starts a comment; dates YYYY-MM-DD; amounts in minor units.
    irr    <name>  one|none|multiple  <k>  r_1 ... r_k  <n>  c_0 ... c_(n-1)        the k rates, ascending
    xirr   <name>  <rate>  <n>  date_1 c_1 ... date_n c_n
    mwr    <name>  <rate>  <start> <end>  <v0> <v1>  <n>  date_1 f_1 ...
    dietz  <name>  <num> <den>  <start> <end>  <v0> <v1>  <n>  date_1 f_1 ...    the exact return, lowest terms
    twr    <name>  <num> <den>  <n>  s_1 f_1 e_1 ...                            the exact return, lowest terms
"""
import datetime
import decimal
import fractions
import pathlib
import random
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NPF_VERSION = "1.0.0"
OUT = ROOT / "tests" / "fixtures" / "finance" / "returns.txt"
LO, HI = -0.999999, 999999.0   # the rates core searches


def g(v):
    return "%.17g" % float(v)


def day(s):
    return datetime.date.fromisoformat(s)


def rates_in_range(np, flows):
    """The real rates r in [LO, HI] at which sum c_t x^t == 0, x = 1 / (1 + r), from numpy.roots."""
    coeffs = list(reversed(flows))            # numpy.roots wants the highest power first
    while coeffs and coeffs[0] == 0:
        coeffs.pop(0)
    out = []
    for x in np.roots(coeffs) if len(coeffs) > 1 else []:
        if abs(x.imag) < 1e-9 and x.real > 0:
            r = 1 / x.real - 1
            if LO <= r <= HI:
                out.append(r)
    return sorted(out)


def decimal_rate(flows):
    """flows: [(days from the first, amount)]; the one r with sum c (1 + r) ** -(d / 365) == 0, by bisection."""
    D = decimal.Decimal
    with decimal.localcontext() as ctx:
        ctx.prec = 60

        def npv(r):
            return sum(D(c) * (1 + r) ** (-(D(d) / 365)) for d, c in flows)

        lo, hi = D("-0.999999"), D("1000")
        flo = npv(lo)
        for _ in range(400):
            mid = (lo + hi) / 2
            fm = npv(mid)
            if fm == 0:
                return mid
            if (fm < 0) == (flo < 0):
                lo, flo = mid, fm
            else:
                hi = mid
            if hi - lo < D("1e-40"):
                break
        return (lo + hi) / 2


def render(np, npf):
    lines = ["# generated by scripts/generate_returns_fixtures.py with numpy-financial %s; do not edit" % npf.__version__,
             "# irr / xirr / mwr / dietz / twr records: see the script's docstring"]
    rng = random.Random(20261126)

    def irr(name, flows):
        roots = rates_in_range(np, flows)
        if len(roots) == 1:
            value = float(npf.irr(flows))
            if abs(value - roots[0]) > 1e-9 * max(1.0, abs(value)):
                raise SystemExit("numpy-financial and numpy.roots disagree on %s: %r %r" % (name, value, roots))
            status, roots = "one", [value]
        else:
            status = "none" if not roots else "multiple"
        lines.append("\t".join(["irr", name, status, str(len(roots))] + [g(r) for r in roots] +
                               [str(len(flows))] + [g(c) for c in flows]))

    irr("textbook", [-100, 39, 59, 55, 20])
    irr("bond_at_a_discount", [-950, 50, 50, 50, 50, 1050])
    irr("a_loss", [-100, 10, 10, 10])
    irr("leading_zeros", [0, 0, -500, 100, 200, 300])
    irr("tripled", [-1, 3])
    irr("nearly_everything_lost", [-100, 1])
    irr("breaks_even", [-100, 50, 50])
    irr("received_first", [100, -30, -30, -50])
    irr("all_received", [100, 50])
    irr("all_paid", [-100, -50, 0])
    irr("two_rates", [-100, 230, -132])
    irr("three_rates", [float(c) for c in np.round(np.poly([1.05, 1.15, 1.3]) * -1000, 6)])
    irr("two_changes_no_rate", [100, -300, 250])
    monthly = [-120000] + [rng.randint(800, 2500) for _ in range(119)] + [rng.randint(60000, 90000)]
    irr("monthly_ten_years", monthly)
    quarterly = [-rng.randint(10000, 50000)] + [rng.randint(-2000, 4000) for _ in range(19)] + [60000]
    irr("quarterly_mixed", quarterly)

    def xirr(name, dated):
        first = day(dated[0][0])
        rate = decimal_rate([((day(d) - first).days, c) for d, c in dated])
        lines.append("\t".join(["xirr", name, g(rate), str(len(dated))] + [v for d, c in dated for v in (d, str(c))]))

    xirr("spreadsheet_example", [("2026-01-01", -10000), ("2026-03-01", 2750), ("2026-10-30", 4250),
                                 ("2027-02-15", 3250), ("2027-04-01", 2750)])
    xirr("same_day_flows", [("2026-02-01", -5000), ("2026-02-01", -5000), ("2026-08-01", 3000), ("2027-02-01", 8000)])
    xirr("a_loss_over_two_years", [("2025-06-30", -100000), ("2026-06-30", 2000), ("2027-06-30", 80000)])
    xirr("one_week", [("2026-11-02", -100000), ("2026-11-09", 100500)])
    start = day("2021-01-04")
    dated = [(start.isoformat(), -rng.randint(50000, 150000))]
    for _ in range(18):
        start += datetime.timedelta(days=rng.randint(20, 120))
        dated.append((start.isoformat(), rng.randint(1000, 9000)))
    dated.append(((start + datetime.timedelta(days=90)).isoformat(), rng.randint(60000, 140000)))
    xirr("random_five_years", dated)

    def mwr(name, begin, end, v0, v1, flows):
        b = day(begin)
        investor = [(0, -v0)] + [((day(d) - b).days, -f) for d, f in flows] + [((day(end) - b).days, v1)]
        rate = decimal_rate(investor)
        lines.append("\t".join(["mwr", name, g(rate), begin, end, str(v0), str(v1), str(len(flows))] +
                               [v for d, f in flows for v in (d, str(f))]))

    mwr("no_flows", "2026-01-01", "2026-12-31", 1000000, 1080000, [])
    mwr("a_contribution", "2026-01-01", "2026-12-31", 1000000, 1650000, [("2026-07-01", 500000)])
    mwr("a_withdrawal", "2026-01-01", "2026-06-30", 1000000, 760000, [("2026-03-15", -300000)])

    def dietz(name, begin, end, v0, v1, flows):
        b, e = day(begin), day(end)
        D = (e - b).days
        F = fractions.Fraction
        gain = F(v1 - v0 - sum(f for _, f in flows))
        capital = F(v0) + sum(F(D - (day(d) - b).days, D) * f for d, f in flows)
        r = gain / capital
        lines.append("\t".join(["dietz", name, str(r.numerator), str(r.denominator), begin, end, str(v0), str(v1),
                                str(len(flows))] + [v for d, f in flows for v in (d, str(f))]))

    dietz("no_flows", "2026-01-01", "2026-03-31", 1000000, 1031250, [])
    dietz("mid_quarter_contribution", "2026-01-01", "2026-03-31", 1000000, 1550000, [("2026-02-15", 500000)])
    dietz("first_and_last_day", "2026-04-01", "2026-06-30", 250000, 400000, [("2026-04-01", 100000), ("2026-06-30", 40000)])
    dietz("a_withdrawal", "2026-07-01", "2026-09-30", 800000, 610000, [("2026-08-20", -250000)])
    b = day("2026-01-01")
    flows = sorted(((b + datetime.timedelta(days=rng.randint(0, 364))).isoformat(), rng.randint(-40000, 90000))
                   for _ in range(12))
    dietz("random_year", "2026-01-01", "2026-12-31", 2000000, 2250000 + sum(f for _, f in flows), flows)

    def twr(name, periods):
        F = fractions.Fraction
        growth = F(1)
        for s, f, e in periods:
            growth *= F(e, s + f)
        r = growth - 1
        lines.append("\t".join(["twr", name, str(r.numerator), str(r.denominator), str(len(periods))] +
                               [str(v) for p in periods for v in p]))

    twr("one_period", [(1000000, 0, 1050000)])
    twr("three_months", [(1000000, 0, 1010000), (1010000, 500000, 1530000), (1530000, -200000, 1320000)])
    twr("a_loss_then_a_gain", [(100000, 0, 80000), (80000, 0, 100000)])
    values = []
    v = 500000
    for _ in range(4):
        f = rng.randint(-50000, 100000)
        e = (v + f) * rng.randint(95, 108) // 100
        values.append((v, f, e))
        v = e
    twr("random_quarters", values)
    return "\n".join(lines) + "\n"


def same(a, b):
    """The two fixtures agree: identical text but for numbers, which agree to a relative 1e-12."""
    la, lb = a.splitlines(), b.splitlines()
    if len(la) != len(lb):
        return False
    for x, y in zip(la, lb):
        if x.startswith("#") or y.startswith("#"):
            if x.split(" with numpy-financial")[0] != y.split(" with numpy-financial")[0]:
                return False
            continue
        fx, fy = x.split("\t"), y.split("\t")
        if len(fx) != len(fy):
            return False
        for u, v in zip(fx, fy):
            if u == v:
                continue
            try:
                p, q = float(u), float(v)
            except ValueError:
                return False
            if abs(p - q) > 1e-12 * max(1.0, abs(p)):
                return False
    return True


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit("usage: generate_returns_fixtures.py [--check]")
    try:
        import numpy as np
        import numpy_financial as npf
    except ImportError:
        np = npf = None
    if npf is None or npf.__version__ != NPF_VERSION:
        if check:
            print(f"returns fixtures: skipped, numpy-financial=={NPF_VERSION} is not installed")
            return 0
        sys.exit(f"generate_returns_fixtures: needs numpy-financial=={NPF_VERSION}")
    text = render(np, npf)
    if check:
        ok = OUT.exists() and same(OUT.read_text(encoding="utf-8"), text)
        print("returns fixtures: " + ("up to date" if ok else "DIFFER"))
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count(chr(10)) - 2} records")
    return 0


if __name__ == "__main__":
    sys.exit(main())
