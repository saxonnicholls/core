"""Write include/snicholls/core/detail/e164_country_codes.hpp, the E.164 country calling codes of phone_number.hpp.

Source: the metadata of libphonenumber, through its Python port `phonenumbers`, pinned to PHONENUMBERS_VERSION below.
Why not the ITU list (the annex to ITU-T E.164 in the Operational Bulletin):

- The tests check phone_number.hpp against `phonenumbers` itself (scripts/generate_e164_fixtures.py), so taking the
  table from the same pinned release means the table and the oracle can never disagree about which codes exist.
- It is machine-readable, versioned and pinnable; the ITU list is a document (Word / PDF) amended by bulletins.
- It carries, per country, the national (trunk) prefix, which is what decides whether a leading 0 after the country
  code is the trunk prefix that an E.164 number never contains.

The difference from the ITU list: libphonenumber lists only the codes that have a numbering plan in use, so codes the
ITU holds as spare, reserved or assigned to trials without a public numbering plan are unknown here, and a number
under them is refused (phone_errc::unknown_country_code).

Two steps, so that the header can be checked on any machine without `phonenumbers` installed:

    1. Extract, once per pinned release, into the committed, dated snapshot scripts/data/e164/country_codes.txt:

         python3 -m pip install phonenumbers==9.0.44
         scripts/generate_e164_country_codes.py --extract

    2. Render the header from the snapshot:

         scripts/generate_e164_country_codes.py            # writes the header
         scripts/generate_e164_country_codes.py --check    # exits 1 if the committed header differs (a CTest);
                                                           # with phonenumbers 9.0.44 installed it also re-extracts
                                                           # and compares the snapshot

Snapshot format (tab-separated, '#' starts a comment): `code trunk_zero regions`, where code is the country calling
code, trunk_zero is 1 when the national prefix for parsing of the code's main region matches a leading 0 (the
trunk prefix 0 of most of the world, never part of the E.164 number), and regions are the ISO 3166 region codes
sharing it, the main region first ("001" for the non-geographic codes).

Never edit the generated header or the snapshot by hand.
"""
import datetime
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PHONENUMBERS_VERSION = "9.0.44"
DATA = ROOT / "scripts" / "data" / "e164" / "country_codes.txt"
OUT = ROOT / "include" / "snicholls" / "core" / "detail" / "e164_country_codes.hpp"


def phonenumbers_or_none():
    try:
        import phonenumbers
    except ImportError:
        return None
    return phonenumbers if phonenumbers.__version__ == PHONENUMBERS_VERSION else None


def extract_rows(pn):
    from phonenumbers import PhoneMetadata
    from phonenumbers.phonenumberutil import COUNTRY_CODE_TO_REGION_CODE

    rows = []
    for code in sorted(COUNTRY_CODE_TO_REGION_CODE):
        regions = COUNTRY_CODE_TO_REGION_CODE[code]
        md = PhoneMetadata.metadata_for_region_or_calling_code(code, regions[0])
        npfp = md.national_prefix_for_parsing
        trunk_zero = bool(npfp) and re.match(npfp, "0123456789012") is not None
        rows.append((code, int(trunk_zero), list(regions)))
    return rows


def snapshot_text(rows, date):
    lines = [f"# E.164 country calling codes, extracted {date} from phonenumbers {PHONENUMBERS_VERSION} "
             "(libphonenumber metadata).",
             "# GENERATED by scripts/generate_e164_country_codes.py --extract - do not edit by hand.",
             "# code<TAB>trunk_zero<TAB>regions (main region first; 001 = non-geographic)"]
    lines += [f"{code}\t{tz}\t{' '.join(regions)}" for code, tz, regions in rows]
    return "\n".join(lines) + "\n"


def read_snapshot():
    text = DATA.read_text(encoding="utf-8")
    m = re.search(r"extracted (\d{4}-\d{2}-\d{2}) from phonenumbers ([0-9.]+)", text)
    if not m or m.group(2) != PHONENUMBERS_VERSION:
        sys.exit(f"generate_e164_country_codes: {DATA} is not a phonenumbers {PHONENUMBERS_VERSION} snapshot")
    rows = []
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        code, tz, regions = line.split("\t")
        rows.append((int(code), int(tz), regions.split(" ")))
    return m.group(1), rows


def check_rows(rows):
    codes = [r[0] for r in rows]
    if codes != sorted(set(codes)) or not all(1 <= c <= 999 for c in codes):
        sys.exit("generate_e164_country_codes: codes must be unique, ascending, 1 to 3 digits")
    texts = [str(c) for c in codes]
    for a in texts:
        for b in texts:
            if a != b and b.startswith(a):
                sys.exit(f"generate_e164_country_codes: {a} is a prefix of {b}: the codes must be prefix-free")


def render(date, rows):
    check_rows(rows)
    out = [
        "//",
        "//  e164_country_codes.hpp",
        "//  snicholls-core",
        "//",
        "//  Copyright 2010-2026 Saxon Herschel Nicholls",
        "//",
        "",
        "/// \\file",
        "/// \\brief Generated E.164 country calling codes for phone_number.hpp. Never edit by hand.",
        "/// \\ingroup core",
        "///",
        "/// Written by scripts/generate_e164_country_codes.py from scripts/data/e164/country_codes.txt, extracted",
        f"/// {date} from the metadata of libphonenumber in the Python package phonenumbers {PHONENUMBERS_VERSION}. The CTest",
        "/// generated.e164_country_codes_up_to_date fails if this file differs from what the generator writes. Not",
        "/// public API.",
        "",
        "#ifndef snicholls_core_detail_e164_country_codes_hpp",
        "#define snicholls_core_detail_e164_country_codes_hpp",
        "",
        "#include <cstdint>",
        "",
        "namespace snicholls::detail::e164",
        "{",
        "",
        "/// The release of phonenumbers the table was extracted from.",
        f"inline constexpr char source[] = \"phonenumbers {PHONENUMBERS_VERSION}\";",
        "",
        "/// The date of the extract.",
        f"inline constexpr char snapshot_date[] = \"{date}\";",
        "",
        "/// One country calling code: the code, and whether a leading 0 after it is the trunk prefix.",
        "struct country_code_entry",
        "{",
        "    std::uint16_t code;   ///< 1 to 999",
        "    bool trunk_zero;   ///< a national significant number under this code never starts with 0",
        "};",
        "",
        "/// Every assigned country calling code, ascending; the regions sharing it follow in a comment.",
        "inline constexpr country_code_entry country_codes[] = {",
    ]
    for code, tz, regions in rows:
        out.append(f"    {{{code}, {'true' if tz else 'false'}}},   // {' '.join(regions)}")
    out += [
        "};",
        "",
        "} // namespace snicholls::detail::e164",
        "",
        "#endif /* snicholls_core_detail_e164_country_codes_hpp */",
    ]
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    if args == ["--extract"]:
        pn = phonenumbers_or_none()
        if pn is None:
            sys.exit(f"generate_e164_country_codes: --extract needs phonenumbers=={PHONENUMBERS_VERSION}")
        rows = extract_rows(pn)
        check_rows(rows)
        DATA.parent.mkdir(parents=True, exist_ok=True)
        DATA.write_text(snapshot_text(rows, datetime.date.today().isoformat()), encoding="utf-8")
        print(f"wrote {DATA.relative_to(ROOT)}: {len(rows)} codes")
        return 0
    if args == ["--check"]:
        date, rows = read_snapshot()
        failed = False
        if OUT.read_text(encoding="utf-8") != render(date, rows):
            print(f"{OUT.relative_to(ROOT)} differs from what scripts/generate_e164_country_codes.py writes")
            failed = True
        pn = phonenumbers_or_none()
        if pn is None:
            print(f"snapshot: not re-extracted, phonenumbers=={PHONENUMBERS_VERSION} is not installed")
        elif extract_rows(pn) != rows:
            print(f"{DATA.relative_to(ROOT)} differs from phonenumbers {PHONENUMBERS_VERSION}")
            failed = True
        print("e164 country codes: " + ("DIFFER" if failed else "up to date"))
        return 1 if failed else 0
    if args:
        sys.exit("usage: generate_e164_country_codes.py [--check | --extract]")
    date, rows = read_snapshot()
    OUT.write_text(render(date, rows), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} codes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
