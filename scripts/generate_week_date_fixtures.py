"""Generate the oracle fixture for include/snicholls/core/time/week_date.hpp (tests/fixtures/time/week_date.txt).

Every expected value comes from Python's standard library, never from core: `datetime.date.isocalendar()` for the
week date of a day and `datetime.date.fromisocalendar()` for the way back (and its ValueError for a week that does
not exist). The days are every day from 24 December to 7 January around each new year from 1995 to 2035, and
pseudo-random days (fixed seed) over the years 1 to 9999; the week dates refused are week 53 of every year from
1995 to 2035 that has only 52, week 0 and week 54.

    ./scripts/generate_week_date_fixtures.py           rewrite the fixture
    ./scripts/generate_week_date_fixtures.py --check   exit 1 if the committed fixture differs from this script's output

Format: tab-separated, '#' starts a comment: `day date year week weekday` for a day and its week date, and
`invalid year week weekday` for a week date fromisocalendar refuses.
"""
import datetime
import pathlib
import random
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "fixtures" / "time" / "week_date.txt"


def render():
    lines = ["# generated by scripts/generate_week_date_fixtures.py from Python's datetime; do not edit\n",
             "# day\tdate\tyear\tweek\tweekday | invalid\tyear\tweek\tweekday\n"]
    days = set()
    for y in range(1995, 2036):
        start = datetime.date(y - 1, 12, 24).toordinal()
        days.update(range(start, start + 15))
    rng = random.Random(20261123)
    days.update(rng.randint(datetime.date(1, 1, 4).toordinal(), datetime.date(9999, 12, 28).toordinal()) for _ in range(800))
    for o in sorted(days):
        d = datetime.date.fromordinal(o)
        y, w, wd = d.isocalendar()
        assert datetime.date.fromisocalendar(y, w, wd) == d
        lines.append("day\t%s\t%d\t%d\t%d\n" % (d.isoformat(), y, w, wd))
    for y in range(1995, 2036):
        for w in (0, 53, 54):
            try:
                datetime.date.fromisocalendar(y, w, 1)
            except ValueError:
                lines.append("invalid\t%d\t%d\t1\n" % (y, w))
    return "".join(lines)


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit("usage: generate_week_date_fixtures.py [--check]")
    text = render()
    if check:
        same = OUT.read_text(encoding="utf-8") == text
        print("week date fixtures: " + ("up to date" if same else "DIFFER"))
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count(chr(10)) - 2} cases")
    return 0


if __name__ == "__main__":
    sys.exit(main())
