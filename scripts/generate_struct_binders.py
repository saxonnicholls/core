"""Generate include/snicholls/core/detail/struct_binders.hpp.

One structured-binding specialisation per member count, 0..MAX. Identifier lists are built by
chained macros, so the header stays ~20 KB instead of ~400 KB of spelled-out names.

    ./scripts/generate_struct_binders.py [MAX]   (default 256; must match SNICHOLLS_MAX_STRUCT_MEMBERS)
    ./scripts/generate_struct_binders.py --check  (exit 1 if the committed header is out of date)
"""
import pathlib
import sys

CHECK = "--check" in sys.argv
ARGS = [a for a in sys.argv[1:] if a != "--check"]
MAX = int(ARGS[0]) if ARGS else 256
OUT = pathlib.Path(__file__).resolve().parent.parent / "include/snicholls/core/detail/struct_binders.hpp"

lines = [
    "//",
    "//  struct_binders.hpp",
    "//  snicholls-core",
    "//",
    "//  Copyright 2010-2026 Saxon Herschel Nicholls",
    "//",
    "",
    "// GENERATED by scripts/generate_struct_binders.py - do not edit by hand.",
    "//",
    "// binder<N>::tie(s) binds the N members of aggregate s by reference (structured bindings) and",
    "// returns them as std::tuple<M&...> (const-qualified when s is const). constexpr, noexcept.",
    "",
    "#ifndef snicholls_core_detail_struct_binders_hpp",
    "#define snicholls_core_detail_struct_binders_hpp",
    "",
    "#include <cstddef>",
    "#include <tuple>",
    "",
    "#include <snicholls/core/reflect/member_count.hpp>",
    "",
    f"static_assert(SNICHOLLS_MAX_STRUCT_MEMBERS <= {MAX},",
    f'              "SNICHOLLS_MAX_STRUCT_MEMBERS exceeds the generated binders; rerun generate_struct_binders.py");',
    "",
    "namespace snicholls::detail {",
    "",
    "template <std::size_t N>",
    "struct binder;",
    "",
    "template <>",
    "struct binder<0>",
    "{",
    "    template <typename S>",
    "    static constexpr std::tuple<> tie(S&) noexcept { return {}; }",
    "};",
    "",
    "#define SNICHOLLS_DETAIL_M1 m0",
]
lines += [f"#define SNICHOLLS_DETAIL_M{n} SNICHOLLS_DETAIL_M{n - 1}, m{n - 1}" for n in range(2, MAX + 1)]
lines += [
    "",
    "#define SNICHOLLS_DETAIL_BINDER(N)                                                     \\",
    "    template <>                                                                 \\",
    "    struct binder<N>                                                            \\",
    "    {                                                                           \\",
    "        template <typename S>                                                   \\",
    "        static constexpr auto tie(S& s) noexcept                                \\",
    "        {                                                                       \\",
    "            auto& [SNICHOLLS_DETAIL_M##N] = s;                                       \\",
    "            return std::tie(SNICHOLLS_DETAIL_M##N);                                  \\",
    "        }                                                                       \\",
    "    };",
    "",
]
lines += [f"SNICHOLLS_DETAIL_BINDER({n})" for n in range(1, MAX + 1)]
lines += ["", "#undef SNICHOLLS_DETAIL_BINDER"]
lines += [f"#undef SNICHOLLS_DETAIL_M{n}" for n in range(1, MAX + 1)]
lines += ["", "} // namespace snicholls::detail", "", "#endif /* snicholls_core_detail_struct_binders_hpp */", ""]

text = "\n".join(lines)
if CHECK:
    if not OUT.exists() or OUT.read_text() != text:
        print(f"{OUT} is out of date: run scripts/generate_struct_binders.py")
        sys.exit(1)
    print(f"{OUT} is up to date")
else:
    OUT.write_text(text)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, 0..{MAX} members)")
