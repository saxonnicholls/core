#  snicholls-core
#
#  Copyright 2010-2026 Saxon Herschel Nicholls
#
#  Writes tests/fixtures/ml/bpe_fixture.txt: a byte-level BPE vocabulary trained by rustbpe on the corpus
#  below with the GPT-4 split pattern, and texts split into pieces with each piece's tokens as tiktoken
#  encodes them. The pieces come from the same pattern through Python's regex module, so the fixture tests
#  core's byte-pair merge and nothing else. Every text is checked three ways before it is written: tiktoken's
#  tokens, rustbpe's tokens, and the concatenation of the pieces' tokens must all agree.
#
#  Needs tiktoken, rustbpe and regex (pip install tiktoken rustbpe regex), unlike core's other generators, so CI does not
#  rerun it; run it by hand after changing the corpus, and commit the result:
#
#      python scripts/generate_bpe_fixture.py            # writes the fixture
#      python scripts/generate_bpe_fixture.py --check    # exits 1 if the committed fixture differs

import base64
import importlib.metadata
import pathlib
import sys

import regex
import rustbpe
import tiktoken

GPT4_PATTERN = (r"""'(?i:[sdmt]|ll|ve|re)|[^\r\n\p{L}\p{N}]?+\p{L}+|\p{N}{1,3}| ?[^\s\p{L}\p{N}]++[\r\n]*|\s*[\r\n]|\s+(?!\S)|\s+""")
VOCAB_SIZE = 512

CORPUS = [
    "The quick brown fox jumps over the lazy dog. The dog was not amused, and the fox ran on.",
    "It's a truth universally acknowledged that we'll tokenize what they've written, and you're reading it.",
    "In 2026 the price was 1,234.56; by 2027 it was 98,765.4321 - a 7900% move. Call 555-0100 or 1-800-555-0199.",
    "def tokenize(text: str) -> list[int]:\n    return [rank(piece) for piece in split(text)]\n\n",
    "template <typename T> constexpr T sigmoid(T x) { return T(1) / (T(1) + exp(-x)); }",
    "for (std::size_t i = 0; i < n; ++i) {\n\tsum += x[i] * y[i];\n}\n",
    "Ünïcödé àccents, naïve café, façade; Straße and Øresund; Ελληνικά, русский, 中文分词, 日本語のテキスト.",
    "Emoji 🙂🚀🔥 and flags 🇦🇺🇳🇿 are several code points; combining é marks too.",
    "    indented    with   runs of     spaces   \n\n\n   and   blank lines\r\nand CRLF\r\n",
    "SELECT name, SUM(amount) FROM trades WHERE ts >= '2026-01-01' GROUP BY name ORDER BY 2 DESC;",
    "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa abababababababab xyzxyzxyzxyz 000000000000 1111 22222222",
    "<html><body><p class=\"note\">Hello, world!</p></body></html> {\"key\": [1, 2, 3], \"ok\": true}",
] * 20

TEXTS = CORPUS[:12] + [
    "",
    " ",
    "a",
    "The foxes' jumps weren't quick.",
    "Unseen words: zygote quixotic pneumonoultramicroscopic.",
    "Numbers 3.14159265358979 and 12345678901234567890.",
    "Mixed 中文 and English, émigré résumé, 🙂🙂🙂.",
    "\x00\x01\x02 control bytes \x7f and tabs\t\t\t.",
    "x" * 300,
]

FIXTURE = pathlib.Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "ml" / "bpe_fixture.txt"


def b64(b: bytes) -> str:
    return base64.b64encode(b).decode("ascii") if b else "-"


def build() -> str:
    tok = rustbpe.Tokenizer()
    tok.train_from_iterator(iter(CORPUS), VOCAB_SIZE, pattern=GPT4_PATTERN)
    ranks = {bytes(k): v for k, v in tok.get_mergeable_ranks()}
    enc = tiktoken.Encoding(name="fixture", pat_str=GPT4_PATTERN, mergeable_ranks=ranks, special_tokens={})

    lines = [
        "# Generated by scripts/generate_bpe_fixture.py - do not edit.",
        f"# A byte-level BPE vocabulary of {len(ranks)} tokens trained by rustbpe {importlib.metadata.version('rustbpe')}"
        f" with the GPT-4 split pattern; tokens as tiktoken {tiktoken.__version__} encodes them.",
        "# vocab <base64 bytes> <rank> | piece <base64 bytes> <tokens...> | text <base64 bytes> <tokens...>",
    ]
    for k, v in sorted(ranks.items(), key=lambda kv: kv[1]):
        lines.append(f"vocab {b64(k)} {v}")
    for text in TEXTS:
        tokens = enc.encode_ordinary(text)
        if tok.encode(text) != tokens:
            sys.exit(f"rustbpe and tiktoken disagree on {text!r}")
        joined = []
        pieces = split_pieces(text)
        for piece in pieces:
            piece_tokens = enc.encode_ordinary(piece.decode("utf-8", errors="surrogateescape")) if is_utf8(piece) else None
            if piece_tokens is None:
                sys.exit(f"a piece of {text!r} is not UTF-8")
            joined += piece_tokens
            lines.append(f"piece {b64(piece)} " + " ".join(map(str, piece_tokens)))
        if joined != tokens:
            sys.exit(f"the pieces of {text!r} do not concatenate to its tokens")
        lines.append(f"text {b64(text.encode())} " + " ".join(map(str, tokens)))
    return "\n".join(lines) + "\n"


def is_utf8(b: bytes) -> bool:
    try:
        b.decode("utf-8")
        return True
    except UnicodeDecodeError:
        return False


def split_pieces(text: str) -> list[bytes]:
    return [m.encode("utf-8") for m in regex.findall(GPT4_PATTERN, text)]


def main() -> int:
    out = build()
    if "--check" in sys.argv:
        if not FIXTURE.exists() or FIXTURE.read_text() != out:
            print(f"{FIXTURE} is out of date: run scripts/generate_bpe_fixture.py")
            return 1
        print("bpe fixture up to date")
        return 0
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(out)
    print(f"wrote {FIXTURE} ({out.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
