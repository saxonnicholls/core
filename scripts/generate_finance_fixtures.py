"""Generate the oracle fixtures for include/snicholls/core/finance/day_count.hpp and finance/business_day.hpp
(tests/fixtures/finance/day_count.txt and business_day.txt).

Every expected value comes from QuantLib's Python package, pinned to QUANTLIB_VERSION below, never from core:

- day_count.txt: for each pair of dates, `dayCount` and `yearFraction` of Actual360, Actual365Fixed,
  Thirty360(BondBasis), Thirty360(European) and ActualActual(ISDA). The pairs are every ordered pair of a set of
  month ends, leap days and year ends in 2023 and 2024, and pseudo-random pairs (fixed seed) over 1901 to 2198,
  within QuantLib's date range (ACT/ACT reads 1 January of the next year), some with the end before the start.
  The year fraction is written with 17 significant digits; core's exact fraction, rounded once, must be within
  1e-15 of it, relative (QuantLib sums ACT/ACT in doubles).
- business_day.txt: `Calendar.adjust` under Following, ModifiedFollowing, Preceding, ModifiedPreceding and
  Unadjusted, for the WeekendsOnly calendar and for TARGET, over every day within four days of a month boundary
  in 2023 to 2026 and of a TARGET holiday. TARGET's weekday holidays over those years are listed in the file
  (`holiday` lines), so the test builds the same calendar from them: the holidays are test data, not core's.

    ./scripts/generate_finance_fixtures.py           rewrite the fixtures (needs QuantLib==1.44)
    ./scripts/generate_finance_fixtures.py --check   exit 1 if the committed fixtures differ from this script's
                                                     output; skipped (exit 0) without QuantLib 1.44

Format: tab-separated, '#' starts a comment.
  day_count.txt:    start end, then days and year fraction for act_360, act_365_fixed, thirty_360, thirty_e_360,
                    act_act_isda (12 fields).
  business_day.txt: `holiday date` lines, then `calendar date unadjusted following modified_following preceding
                    modified_preceding` lines, calendar `weekends` or `target`.
"""
import datetime
import pathlib
import random
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
QUANTLIB_VERSION = "1.44"
OUT = ROOT / "tests" / "fixtures" / "finance"
HEADER = "# generated by scripts/generate_finance_fixtures.py from QuantLib {}; do not edit\n"


def iso(d):
    return "%04d-%02d-%02d" % (d.year(), d.month(), d.dayOfMonth())


def day_count(ql):
    conventions = [ql.Actual360(), ql.Actual365Fixed(), ql.Thirty360(ql.Thirty360.BondBasis),
                   ql.Thirty360(ql.Thirty360.European), ql.ActualActual(ql.ActualActual.ISDA)]
    edges = []
    for y in (2023, 2024):
        for m, d in ((1, 1), (1, 30), (1, 31), (2, 27), (2, 28), (2, 29), (3, 1), (3, 30), (3, 31), (6, 30),
                     (12, 30), (12, 31)):
            if m == 2 and d == 29 and y % 4:
                continue
            edges.append(ql.Date(d, m, y))
    pairs = [(a, b) for a in edges for b in edges if a <= b]
    rng = random.Random(20261123)
    first, last = ql.Date(1, 1, 1901).serialNumber(), ql.Date(31, 12, 2198).serialNumber()
    for i in range(300):
        a = rng.randint(first, last)
        span = rng.choice((rng.randint(0, 40), rng.randint(0, 400), rng.randint(0, 4000), rng.randint(0, 40000)))
        b = min(a + span, last)
        if i % 5 == 0:
            a, b = b, a
        pairs.append((ql.Date(a), ql.Date(b)))
    lines = [HEADER.format(QUANTLIB_VERSION),
             "# start\tend\tact_360 days\tyf\tact_365_fixed days\tyf\tthirty_360 days\tyf\tthirty_e_360 days\tyf"
             "\tact_act_isda days\tyf\n"]
    for a, b in pairs:
        fields = [iso(a), iso(b)]
        for c in conventions:
            fields += [str(c.dayCount(a, b)), "%.17g" % c.yearFraction(a, b)]
        lines.append("\t".join(fields) + "\n")
    return "".join(lines)


def business_day(ql):
    target, weekends = ql.TARGET(), ql.WeekendsOnly()
    start, end = ql.Date(1, 1, 2023), ql.Date(31, 12, 2026)
    holidays = list(ql.Calendar.holidayList(target, start, end, False))
    days = set()
    for y in range(2023, 2027):
        for m in range(1, 13):
            boundary = datetime.date(y, m, 1).toordinal()
            days.update(range(boundary - 4, boundary + 4))
    for h in holidays:
        o = datetime.date(h.year(), h.month(), h.dayOfMonth()).toordinal()
        days.update(range(o - 4, o + 5))
    conventions = [ql.Unadjusted, ql.Following, ql.ModifiedFollowing, ql.Preceding, ql.ModifiedPreceding]
    lines = [HEADER.format(QUANTLIB_VERSION), "# holiday\tdate: TARGET's weekday holidays, 2023 to 2026\n"]
    lines += ["holiday\t%s\n" % iso(h) for h in holidays]
    lines.append("# calendar\tdate\tunadjusted\tfollowing\tmodified_following\tpreceding\tmodified_preceding\n")
    for name, cal in (("weekends", weekends), ("target", target)):
        for o in sorted(days):
            g = datetime.date.fromordinal(o)
            d = ql.Date(g.day, g.month, g.year)
            lines.append("\t".join([name, iso(d)] + [iso(cal.adjust(d, c)) for c in conventions]) + "\n")
    return "".join(lines)


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit("usage: generate_finance_fixtures.py [--check]")
    try:
        import QuantLib as ql
    except ImportError:
        ql = None
    if ql is None or ql.__version__ != QUANTLIB_VERSION:
        if check:
            print(f"finance fixtures: skipped, QuantLib=={QUANTLIB_VERSION} is not installed")
            return 0
        sys.exit(f"generate_finance_fixtures: needs QuantLib=={QUANTLIB_VERSION}")
    files = {"day_count.txt": day_count(ql), "business_day.txt": business_day(ql)}
    if check:
        differ = [n for n, t in files.items() if (OUT / n).read_text(encoding="utf-8") != t]
        print("finance fixtures: " + ("DIFFER: " + ", ".join(differ) if differ else "up to date"))
        return 1 if differ else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for n, t in files.items():
        (OUT / n).write_text(t, encoding="utf-8")
        print(f"wrote {(OUT / n).relative_to(ROOT)}: {sum(1 for l in t.splitlines() if not l.startswith('#'))} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
